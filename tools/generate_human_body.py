def generate_human_body(variation: int = 0, bone_geometry_format: str = "indexed_mesh") -> dict:
    r = Reg()
    proportions = gen_proportions(variation)
    weight = proportions["weight"]
    height = proportions["totalHeight"]
    sex = proportions.get("biologicalSex", "male")

    skeleton = gen_skeleton(r, weight, height)
    joints = gen_joints(r)
    nerves = gen_nerves(r)
    tendons, muscles = gen_tendons_and_muscles(r)
    organs = gen_organs(r, sex)
    vascular = gen_vascular(r)

    # Resolve bloodSupply.primaryArteryId for muscles (vascular must exist first).
    # Muscle artery names are generic ("Brachial artery") but vessel names are
    # lateralized ("Brachial artery (R)"). Match strategy:
    #   1. Exact name match
    #   2. Lateralized match: append " (R)" or " (L)" based on muscle side
    #   3. Strip vessel laterality for generic match
    vessel_name_to_id: dict[str, str] = {}
    for v in vascular:
        vessel_name_to_id[v["name"]] = v["id"]
    # Also build a de-lateralized index: "Brachial artery" → first match
    vessel_base_to_id: dict[str, str] = {}
    for v in vascular:
        base = v["name"].replace(" (R)", "").replace(" (L)", "")
        if base not in vessel_base_to_id:
            vessel_base_to_id[base] = v["id"]
    for m in muscles:
        artery_name = m["bloodSupply"]["primaryArteryName"]
        vid = vessel_name_to_id.get(artery_name)
        if not vid:
            # Derive side from muscle name
            side = "(R)" if "(R)" in m["name"] else ("(L)" if "(L)" in m["name"] else "")
            if side:
                vid = vessel_name_to_id.get(f"{artery_name} {side}")
        if not vid:
            vid = vessel_base_to_id.get(artery_name)
        if vid:
            m["bloodSupply"]["primaryArteryId"] = vid

    ligaments = gen_ligaments(r)
    cartilage = gen_cartilage(r)
    segments = gen_segments(r, weight, sex)
    current_pose = gen_current_pose(r)
    saved_poses = gen_saved_poses(r)
    loading = gen_loading_conditions(r, weight)
    ref_frames = _gen_reference_frames(r)
    fbds = _gen_free_body_diagrams(r, loading, weight)
    motion_seqs = _gen_motion_sequences(r)
    rendering = _gen_rendering_layer(r)
    clothing = _gen_clothing(height)
    bone_geometries = gen_bone_geometries(r, geometry_format=bone_geometry_format)

    return {
        "schemaVersion": SCHEMA_VERSION, "id": uid(), "name": f"generated_body_{variation:03d}",
        "proportions": proportions, "skeleton": skeleton, "joints": joints,
        "tendons": tendons, "muscles": muscles, "organs": organs,
        "vascularSystem": vascular, "ligaments": ligaments, "cartilage": cartilage,
        "nerves": nerves, "hair": gen_hair(height), "clothing": clothing,
        "segments": segments, "currentPose": current_pose, "savedPoses": saved_poses,
        "loadingConditions": loading, "derivationGraph": gen_derivation_graph(),
        "constitutiveLaws": gen_constitutive_laws(),
        "referenceFrames": ref_frames,
        "freeBodyDiagrams": fbds,
        "motionSequences": motion_seqs,
        "rendering": rendering,
        "boneGeometries": bone_geometries,
    }

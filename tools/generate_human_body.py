def vec3(x: float = 0, y: float = 0, z: float = 0) -> dict:
    return {"x": round(x, 6), "y": round(y, 6), "z": round(z, 6)}

def unit_vec3(x: float = 0, y: float = 1, z: float = 0) -> dict:
    mag = math.sqrt(x * x + y * y + z * z) or 1.0
    return {"x": round(x / mag, 6), "y": round(y / mag, 6), "z": round(z / mag, 6)}

def identity_quat() -> dict:
    return {"w": 1.0, "x": 0.0, "y": 0.0, "z": 0.0}

def small_tilt_quat(pitch_deg: float = 0, yaw_deg: float = 0, roll_deg: float = 0) -> dict:
    p, y, r = math.radians(pitch_deg / 2), math.radians(yaw_deg / 2), math.radians(roll_deg / 2)
    w = math.cos(p) * math.cos(y) * math.cos(r) + math.sin(p) * math.sin(y) * math.sin(r)
    qx = math.sin(p) * math.cos(y) * math.cos(r) - math.cos(p) * math.sin(y) * math.sin(r)
    qy = math.cos(p) * math.sin(y) * math.cos(r) + math.sin(p) * math.cos(y) * math.sin(r)
    qz = math.cos(p) * math.cos(y) * math.sin(r) - math.sin(p) * math.sin(y) * math.cos(r)
    mag = math.sqrt(w*w + qx*qx + qy*qy + qz*qz)
    return {"w": round(w/mag, 4), "x": round(qx/mag, 4), "y": round(qy/mag, 4), "z": round(qz/mag, 4)}


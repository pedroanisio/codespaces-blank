        xoff = x + sign * (-1.5 + j * 0.8)
        zbase = 15 + j * 0.3
        pp_idx = add(f"{toe_names[j]} proximal phalanx ({side})", "long", "appendicular_lower",
                      mt_idx, 3 if j == 0 else 2.5, 0.7, 0.5, 2, (xoff, y, zbase))

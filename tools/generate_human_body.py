def uid() -> str:
    return str(uuid.uuid4())


def vec3(x: float = 0, y: float = 0, z: float = 0) -> dict:
    return {"x": x, "y": y, "z": z}


def unit_vec3(x: float = 0, y: float = 1, z: float = 0) -> dict:
    mag = math.sqrt(x * x + y * y + z * z) or 1.0
    return {"x": x / mag, "y": y / mag, "z": z / mag}


def identity_quaternion() -> dict:
    return {"w": 1.0, "x": 0.0, "y": 0.0, "z": 0.0}


def random_unit_quaternion() -> dict:
    """Generate a random unit quaternion (uniform over SO(3))."""
    u1, u2, u3 = random.random(), random.random(), random.random()
    w = math.sqrt(1 - u1) * math.sin(2 * math.pi * u2)
    x = math.sqrt(1 - u1) * math.cos(2 * math.pi * u2)
    y = math.sqrt(u1) * math.sin(2 * math.pi * u3)
    z = math.sqrt(u1) * math.cos(2 * math.pi * u3)
    return {"w": w, "x": x, "y": y, "z": z}


def rigid_pose(px: float = 0, py: float = 0, pz: float = 0) -> dict:
    return {
        "position": vec3(px, py, pz),
        "orientation": identity_quaternion(),
    }


def transform(px: float = 0, py: float = 0, pz: float = 0) -> dict:
    return {
        "position": vec3(px, py, pz),
        "rotation": vec3(0, 0, 0),
        "scale": vec3(1, 1, 1),
    }


def color(r: int = 200, g: int = 180, b: int = 160, a: float = 1.0) -> dict:
    return {"r": r, "g": g, "b": b, "a": a}


def symmetric_tensor(xx: float = 1, yy: float = 1, zz: float = 1) -> dict:
    return {"xx": xx, "yy": yy, "zz": zz, "xy": 0, "xz": 0, "yz": 0}


def pick(choices: list[str]) -> str:
    return random.choice(choices)



def gen_proportions(variation: int = 0) -> dict:
    """Generate anthropometrically valid proportions."""
    sex = SEX_OPTIONS[variation % len(SEX_OPTIONS)]
    # Base values for an average adult
    height = random.uniform(155, 195)
    weight = random.uniform(50, 110)
    shoulder_w = random.uniform(35, 50)

    # Ensure arm/height ratio in [0.35, 0.55]
    arm_ratio = random.uniform(0.40, 0.50)
    arm_length = height * arm_ratio

    # Ensure leg/height ratio in [0.40, 0.55]
    leg_ratio = random.uniform(0.44, 0.52)
    leg_length = height * leg_ratio

    head_circ = random.uniform(53, 60)

    muscle_pct = random.uniform(25, 45)
    fat_pct = random.uniform(8, 30)
    # Ensure sum ≤ 75
    if muscle_pct + fat_pct > 74:
        fat_pct = 74 - muscle_pct

    return {
        "biologicalSex": sex,
        "totalHeight": round(height, 1),
        "weight": round(weight, 1),
        "shoulderWidth": round(shoulder_w, 1),
        "armLength": round(arm_length, 1),
        "legLength": round(leg_length, 1),
        "headCircumference": round(head_circ, 1),
        "muscleMassPercentage": round(muscle_pct, 1),
        "fatPercentage": round(fat_pct, 1),
    }


def gen_skeleton(reg: IDRegistry, template_idx: int = 0) -> list[dict]:
    """Generate skeleton bones from template."""
    template = SKELETON_TEMPLATES[template_idx % len(SKELETON_TEMPLATES)]
    bones = []
    for i, bt in enumerate(template):
        bone_id = uid()
        reg.bone_ids.append(bone_id)
        parent_id = reg.bone_ids[bt["parent_idx"]] if bt["parent_idx"] is not None else None
        y_offset = sum(t["length"] for t in template[:i] if t.get("parent_idx") is not None and t["parent_idx"] < i) * 0.3
        bones.append({
            "id": bone_id,
            "name": bt["name"],
            "classification": bt["class"],
            "region": bt["region"],
            "transform": transform(0, y_offset, 0),
            "length": bt["length"],
            "width": bt["width"],
            "mass": round(bt["length"] * bt["width"] * random.uniform(1.5, 4.0), 1),
            "parentBoneId": parent_id,
        })
    return bones



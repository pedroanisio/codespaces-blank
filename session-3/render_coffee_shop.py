def main() -> None:
    parser = argparse.ArgumentParser(
        description="Render a BuildingModel JSON as 2D blueprint + 3D isometric + POV PNGs"
    )
    parser.add_argument(
        "json_file",
        nargs="?",
        default=str(Path(__file__).parent / "pulp-fiction-coffee-shop.json"),
        help="Path to the BuildingModel JSON file (default: pulp-fiction-coffee-shop.json)",
    )
    parser.add_argument(
        "-o", "--output-dir",
        default=str(Path(__file__).parent / "output"),
        help="Output directory for rendered PNGs (default: ./output)",
    )
    parser.add_argument(
        "--blueprint-only", action="store_true",
        help="Only render the 2D blueprint (skip 3D isometric and POVs)",
    )
    parser.add_argument(
        "--iso-only", action="store_true",
        help="Only render the 3D isometric (skip 2D blueprint and POVs)",
    )
    parser.add_argument(
        "--pov-only", action="store_true",
        help="Only render POV viewpoints (skip blueprint and isometric)",
    )
    parser.add_argument(
        "--pov", type=str, default=None,
        help="Render specific viewpoint(s) by name or index (comma-separated). "
             "Use 'all' for all viewpoints, or e.g. '0,2' or 'Booth,Robbery'.",
    )
    parser.add_argument(
        "--scale", type=float, default=40,
        help="Isometric renderer scale factor (default: 40)",
    )
    args = parser.parse_args()

    json_path = Path(args.json_file)
    if not json_path.exists():
        print(f"Error: JSON file not found: {json_path}", file=sys.stderr)
        sys.exit(1)

    out_dir = Path(args.output_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    stem = json_path.stem

    print(f"Loading model from {json_path} ...")
    model, viewpoints, site = load_building_model(str(json_path))
    _apply_diner_palette()

    total_area = sum(s.computed_area() for fl in model.floors for s in fl.spaces)
    total_walls = sum(len(fl.walls) for fl in model.floors)
    total_openings = sum(len(w.openings) for fl in model.floors for w in fl.walls)
    total_spaces = sum(len(fl.spaces) for fl in model.floors)

    print(f"  Title:    {model.title}")
    print(f"  Building: {model.building.name}")
    print(f"  Floors:   {len(model.floors)}")
    print(f"  Spaces:   {total_spaces}  ({total_area:.0f} m²)")
    print(f"  Walls:    {total_walls}  (openings: {total_openings})")
    if site.terrain:
        ttris = sum(len(t.triangles) for t in site.terrain)
        print(f"  Terrain:  {len(site.terrain)} surface(s), {ttris} triangles")
    if site.features:
        print(f"  Features: {len(site.features)}")
    if viewpoints:
        print(f"  ViewPoints: {len(viewpoints)}")
        for i, vp in enumerate(viewpoints):
            print(f"    [{i}] {vp.name} ({vp.projection})")
    print()

    # Determine which renders to produce
    do_blueprint = not (args.iso_only or args.pov_only)
    do_iso = not (args.blueprint_only or args.pov_only)
    do_pov = args.pov_only or args.pov is not None

    # If --pov-only but no --pov specified, render all
    if args.pov_only and args.pov is None:
        args.pov = "all"

    # If no specific flags, render everything including all POVs
    if not (args.blueprint_only or args.iso_only or args.pov_only) and args.pov is None:
        do_pov = True
        args.pov = "all"

    if do_blueprint:
        bp_path = out_dir / f"{stem}-blueprint.png"
        print(f"Rendering 2D blueprint → {bp_path} ...")
        renderer_2d = BlueprintRenderer(model)
        renderer_2d.render(str(bp_path))
        print(f"  Done. {renderer_2d.img_w()}×{renderer_2d.img_h()} px")

    if do_iso:
        iso_path = out_dir / f"{stem}-isometric.png"
        print(f"Rendering 3D isometric → {iso_path} ...")
        renderer_3d = IsometricRenderer(model, scale=args.scale)
        renderer_3d.render(str(iso_path))
        print(f"  Done. {renderer_3d.img_w()}×{renderer_3d.img_h()} px")

    if do_pov and viewpoints:
        # Resolve which viewpoints to render
        selected = _resolve_viewpoints(viewpoints, args.pov)
        if not selected:
            print("  No matching viewpoints found.", file=sys.stderr)
        for vp in selected:
            safe_name = vp.name.lower().replace(" ", "-").replace("/", "-")
            safe_name = "".join(c for c in safe_name if c.isalnum() or c in "-_")[:60]
            pov_path = out_dir / f"{stem}-pov-{safe_name}.png"
            print(f"Rendering POV '{vp.name}' → {pov_path} ...")
            renderer = POVRenderer(model, vp, site=site)
            renderer.render(str(pov_path))
            print(f"  Done. {renderer.IMG_W}×{renderer.IMG_H} px")

    print("\nAll renders complete.")


def _resolve_viewpoints(viewpoints: list[ViewPoint], spec: str) -> list[ViewPoint]:
    """Resolve a viewpoint specifier to a list of ViewPoints."""
    if spec.lower() == "all":
        return viewpoints

    selected = []
    for part in spec.split(","):
        part = part.strip()
        # Try as index
        try:
            idx = int(part)
            if 0 <= idx < len(viewpoints):
                selected.append(viewpoints[idx])
                continue
        except ValueError:
            pass
        # Try as substring match on name
        for vp in viewpoints:
            if part.lower() in vp.name.lower() and vp not in selected:
                selected.append(vp)
    return selected



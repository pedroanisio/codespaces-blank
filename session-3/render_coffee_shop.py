def load_building_model(path: str) -> tuple[BuildingModel, list[ViewPoint], SiteData]:
    """Load a BuildingModel, ViewPoints, and site data from a JSON file.

    Supports both v2.x (BuildingModel root) and v3.x (ProjectSite root).
    For v3, extracts the first building from the `buildings` array.
    """
    with open(path, "r", encoding="utf-8") as f:
        data = json.load(f)

    site = SiteData()

    # Detect v3 ProjectSite: root has `buildings` array instead of `building`
    if "buildings" in data and isinstance(data["buildings"], list):
        # v3.0.0 ProjectSite — extract first building
        if not data["buildings"]:
            raise ValueError("ProjectSite has no buildings")
        bld = data["buildings"][0]
        model = BuildingModel(
            schema_version=data["schemaVersion"],
            id=bld["id"],
            title=bld.get("title", data.get("name", "Untitled")),
            length_unit=_enum_or_default(LengthUnit, bld.get("lengthUnit", data["lengthUnit"])),
            building=_parse_building(bld["building"]),
            floors=[_parse_floor(fl) for fl in bld["floors"]],
            metadata=_parse_metadata(data["metadata"]),
            origin=_parse_point3d({"x": 0, "y": 0, "z": 0}),
            true_north_deg=bld.get("trueNorthDeg", 0),
            up_axis=bld.get("upAxis", "z"),
        )
        # Merge building-level + site-level viewpoints
        # Building-level viewpoints are in building-local coords — offset to site
        pl = bld.get("placement", {})
        ap = pl.get("anchorPoint", {})
        bx, by, bz = ap.get("x", 0), ap.get("y", 0), ap.get("z", 0)
        viewpoints = []
        for vp_data in bld.get("viewPoints", []):
            vp = _parse_viewpoint(vp_data)
            vp.eye = Point3D(vp.eye.x + bx, vp.eye.y + by, vp.eye.z + bz)
            vp.target = Point3D(vp.target.x + bx, vp.target.y + by, vp.target.z + bz)
            viewpoints.append(vp)
        # Site-level viewpoints are already in site coords
        viewpoints += [_parse_viewpoint(vp) for vp in data.get("viewPoints", [])]

        # Extract terrain
        for ts in data.get("terrainSurfaces", []):
            site.terrain.append(_parse_terrain(ts))

        # Extract site features
        for sf in data.get("features", []):
            site.features.append(_parse_site_feature(sf))

        # Extract building placement offset
        pl = bld.get("placement", {})
        ap = pl.get("anchorPoint", {})
        site.placement = BuildingOffset(
            x=ap.get("x", 0), y=ap.get("y", 0), z=ap.get("z", 0)
        )
    else:
        # v2.x BuildingModel root
        model = BuildingModel(
            schema_version=data["schemaVersion"],
            id=data["id"],
            title=data["title"],
            length_unit=_enum_or_default(LengthUnit, data["lengthUnit"]),
            building=_parse_building(data["building"]),
            floors=[_parse_floor(fl) for fl in data["floors"]],
            metadata=_parse_metadata(data["metadata"]),
            origin=_parse_point3d(data.get("origin", {"x": 0, "y": 0, "z": 0})),
            true_north_deg=data.get("trueNorthDeg", 0),
            up_axis=data.get("upAxis", "z"),
        )
        viewpoints = [_parse_viewpoint(vp) for vp in data.get("viewPoints", [])]

    return model, viewpoints, site



def _parse_terrain(d: dict) -> TerrainData:
    mesh = d["mesh"]
    verts = [Point3D(v["x"], v["y"], v["z"]) for v in mesh["vertices"]]
    tris = []
    for t in mesh["triangles"]:
        tris.append(TerrainTriangle(verts[t[0]], verts[t[1]], verts[t[2]]))
    return TerrainData(name=d["name"], triangles=tris)


def _parse_site_feature(d: dict) -> SiteFeatureData:
    sf = SiteFeatureData(
        name=d.get("name", ""),
        kind=d.get("kind", "other"),
        geometry_type=d.get("geometryType", "point"),
    )
    if d.get("position"):
        sf.position = _parse_point3d(d["position"])
    if d.get("path") and d["path"].get("points"):
        sf.path_points = [_parse_point3d(p) for p in d["path"]["points"]]
    if d.get("footprint") and d["footprint"].get("vertices"):
        sf.footprint = [_parse_point2d(v) for v in d["footprint"]["vertices"]]
    sf.height = d.get("heightAboveGround", 0.0)
    sf.canopy_radius = d.get("canopyRadiusUnits", 0.0)
    sf.width = d.get("widthUnits", 0.0)
    return sf



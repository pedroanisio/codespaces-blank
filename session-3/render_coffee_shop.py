def _apply_diner_palette():
    """Extend FILL_COLORS with diner-relevant SpaceUsage mappings."""
    import manhattan_blueprint as mb

    # The coffee shop uses SpaceUsage.commercial, .lobby, .restroom, .storage
    # which aren't in the default apartment palette — add warm diner tones
    extra = {
        SpaceUsage.OTHER: (65, 85, 115),       # general commercial
    }
    # Patch the module-level dict so renderers pick it up
    for k, v in extra.items():
        if k not in mb.FILL_COLORS:
            mb.FILL_COLORS[k] = v



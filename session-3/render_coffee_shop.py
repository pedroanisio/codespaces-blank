def _v3_sub(a: Point3D, b: Point3D) -> tuple[float, float, float]:
    return (a.x - b.x, a.y - b.y, a.z - b.z)


def _v3_cross(a: tuple, b: tuple) -> tuple[float, float, float]:
    return (a[1]*b[2] - a[2]*b[1], a[2]*b[0] - a[0]*b[2], a[0]*b[1] - a[1]*b[0])


def _v3_dot(a: tuple, b: tuple) -> float:
    return a[0]*b[0] + a[1]*b[1] + a[2]*b[2]


def _v3_normalize(v: tuple) -> tuple[float, float, float]:
    mag = math.sqrt(v[0]**2 + v[1]**2 + v[2]**2)
    if mag < 1e-12:
        return (0.0, 0.0, 1.0)
    return (v[0]/mag, v[1]/mag, v[2]/mag)


def _v3_scale(v: tuple, s: float) -> tuple[float, float, float]:
    return (v[0]*s, v[1]*s, v[2]*s)


class POVRenderer:
    """Renders a BuildingModel from a named ViewPoint using software 3D projection."""

    IMG_W = 1600
    IMG_H = 900

    def __init__(self, model: BuildingModel, vp: ViewPoint,
                 site: SiteData | None = None):
        self.model = model
        self.vp = vp
        self.site = site or SiteData()
        self._build_camera()

    def _build_camera(self) -> None:
        """Build a look-at view matrix + perspective projection."""
        vp = self.vp
        # View direction
        fwd = _v3_normalize(_v3_sub(vp.target, vp.eye))
        up = (vp.up.x, vp.up.y, vp.up.z)

        # Camera basis: right, up, forward
        self.cam_right = _v3_normalize(_v3_cross(fwd, up))
        self.cam_up = _v3_normalize(_v3_cross(self.cam_right, fwd))
        self.cam_fwd = fwd
        self.eye = (vp.eye.x, vp.eye.y, vp.eye.z)

        # Perspective params
        self.aspect = self.IMG_W / self.IMG_H
        if vp.projection == "perspective":
            self.fov_scale = 1.0 / math.tan(math.radians(vp.fov_deg / 2))
        else:
            # orthographic/isometric
            h = vp.ortho_height or 20.0
            self.fov_scale = 2.0 / h

    def _project(self, p: Point3D) -> tuple[float, float, float] | None:
        """Project a 3D world point to screen (px_x, px_y, depth). None if behind camera."""
        # World to camera space
        rel = _v3_sub(p, Point3D(*self.eye))
        cx = _v3_dot(rel, self.cam_right)
        cy = _v3_dot(rel, self.cam_up)
        cz = _v3_dot(rel, self.cam_fwd)  # depth along view direction

        if cz < 0.05:
            return None  # behind camera

        if self.vp.projection == "perspective":
            # Perspective divide
            inv_z = self.fov_scale / cz
            sx = cx * inv_z
            sy = cy * inv_z
        else:
            sx = cx * self.fov_scale
            sy = cy * self.fov_scale

        # Normalized device coords → pixel coords
        px = self.IMG_W / 2 + sx * self.IMG_W / (2 * self.aspect)
        py = self.IMG_H / 2 - sy * self.IMG_H / 2

        return (px, py, cz)

    def _project_poly(self, pts: list[Point3D]) -> tuple[list[tuple[int, int]], float] | None:
        """Project N points and return (pixel_points, avg_depth), or None if any behind."""
        projected = []
        total_depth = 0.0
        for p in pts:
            r = self._project(p)
            if r is None:
                return None
            projected.append((int(r[0]), int(r[1])))
            total_depth += r[2]
        return projected, total_depth / len(pts)

    def _project_quad(self, pts: list[Point3D]) -> tuple[list[tuple[int, int]], float] | None:
        return self._project_poly(pts)

    def _project_tri(self, pts: list[Point3D]) -> tuple[list[tuple[int, int]], float] | None:
        return self._project_poly(pts)

    def render(self, path: str) -> str:
        img = Image.new("RGB", (self.IMG_W, self.IMG_H), _POV_BG)
        draw = ImageDraw.Draw(img)

        # Sky gradient
        for y in range(self.IMG_H // 2):
            t = y / (self.IMG_H // 2)
            r = int(_POV_SKY_TOP[0] + (_POV_SKY_BOT[0] - _POV_SKY_TOP[0]) * t)
            g = int(_POV_SKY_TOP[1] + (_POV_SKY_BOT[1] - _POV_SKY_TOP[1]) * t)
            b = int(_POV_SKY_TOP[2] + (_POV_SKY_BOT[2] - _POV_SKY_TOP[2]) * t)
            draw.line([(0, y), (self.IMG_W, y)], fill=(r, g, b))

        # Collect all renderable faces with depths for painter's algorithm
        faces: list[tuple[float, str, list[tuple[int, int]], tuple]] = []
        # (depth, type, pixel_points, color_data)

        ox, oy, oz = self.site.placement.x, self.site.placement.y, self.site.placement.z

        # ── Terrain TIN triangles ────────────────────────────────────────
        for td in self.site.terrain:
            for i, tri in enumerate(td.triangles):
                pts = [tri.v0, tri.v1, tri.v2]
                result = self._project_tri(pts)
                if result:
                    color = _POV_TERRAIN_A if i % 2 == 0 else _POV_TERRAIN_B
                    faces.append((result[1] + 200, "terrain", result[0], color))

        # ── Site features (polygon footprints) ───────────────────────────
        for sf in self.site.features:
            if sf.geometry_type == "polygon" and sf.footprint:
                # Use the terrain base elevation (~30m) but normalize to 0
                fz = 0.01  # just above terrain
                pts = [Point3D(v.x, v.y, fz) for v in sf.footprint]
                result = self._project_quad(pts) if len(pts) == 4 else self._project_tri(pts[:3])
                if result:
                    if sf.kind == "parking_lot":
                        color = _POV_PARKING
                    elif sf.kind in ("existing_structure", "demolished_structure"):
                        color = (55, 60, 75)
                    else:
                        color = _POV_GROUND
                    faces.append((result[1] + 150, "site_poly", result[0], color))

        # ── Building geometry (offset to site coords) ────────────────────
        for floor in self.model.floors:
            z0 = floor.elevation_above_datum

            # Ground plane fallback (only if no terrain)
            if not self.site.terrain:
                ground_pts = [
                    Point3D(-20, -20, z0), Point3D(50, -20, z0),
                    Point3D(50, 40, z0), Point3D(-20, 40, z0),
                ]
                result = self._project_quad(ground_pts)
                if result:
                    faces.append((result[1] + 100, "ground", result[0], _POV_GROUND))

            # Floor slab
            for slab in floor.slabs:
                verts = slab.boundary.outer.vertices
                pts = [Point3D(v.x + ox, v.y + oy, slab.elevation + oz) for v in verts]
                result = self._project_quad(pts)
                if result:
                    faces.append((result[1] + 50, "slab", result[0], _POV_FLOOR))

            # Space floors
            for space in floor.spaces:
                verts = space.boundary.outer.vertices
                pts = [Point3D(v.x + ox, v.y + oy, space.floor_elevation + oz + 0.01) for v in verts]
                result = self._project_quad(pts)
                if result:
                    from manhattan_blueprint import FILL_COLORS, DEFAULT_FILL
                    fill = FILL_COLORS.get(space.usage, DEFAULT_FILL)
                    fill = tuple(min(255, c + 20) for c in fill)
                    faces.append((result[1] + 40, "floor", result[0], fill))

            # Walls (offset applied inside)
            for wall in floor.walls:
                self._collect_wall_faces(faces, wall, ox, oy, oz)

        # Sort by depth — farthest first (painter's algorithm)
        faces.sort(key=lambda f: -f[0])

        # Draw all faces
        for depth, ftype, pixels, color_data in faces:
            if ftype == "terrain":
                draw.polygon(pixels, fill=color_data, outline=_POV_TERRAIN_EDGE)
            elif ftype == "site_poly":
                draw.polygon(pixels, fill=color_data, outline=_POV_PARKING_LINE)
            elif ftype in ("ground", "slab", "floor"):
                draw.polygon(pixels, fill=color_data, outline=_POV_OUTLINE)
            elif ftype == "wall_front":
                draw.polygon(pixels, fill=color_data, outline=_POV_OUTLINE)
            elif ftype == "wall_top":
                draw.polygon(pixels, fill=color_data, outline=_POV_OUTLINE)
            elif ftype == "wall_side":
                draw.polygon(pixels, fill=color_data, outline=_POV_OUTLINE)
            elif ftype == "window":
                draw.polygon(pixels, fill=_POV_WINDOW, outline=_POV_WINDOW_FRAME)
                if len(pixels) == 4:
                    draw.line([pixels[0], pixels[2]], fill=_POV_WINDOW_FRAME, width=1)
                    draw.line([pixels[1], pixels[3]], fill=_POV_WINDOW_FRAME, width=1)
            elif ftype == "door":
                draw.polygon(pixels, fill=_POV_DOOR, outline=_POV_OUTLINE)

        # ── Site features: lines and points (drawn on top of terrain) ────
        self._draw_site_features(draw)

        # Title overlay
        self._draw_overlay(draw)
        img.save(path)
        return path

    def _draw_site_features(self, draw: ImageDraw.Draw) -> None:
        """Draw polyline and point site features on top of the terrain."""
        for sf in self.site.features:
            if sf.geometry_type == "polyline" and sf.path_points:
                # Project and draw the line
                projected = []
                for p in sf.path_points:
                    r = self._project(p)
                    if r:
                        projected.append((int(r[0]), int(r[1])))
                if len(projected) >= 2:
                    if sf.kind == "road":
                        w = max(2, int(sf.width * 2))
                        draw.line(projected, fill=_POV_ROAD, width=w)
                        # Center stripe
                        draw.line(projected, fill=_POV_ROAD_STRIPE, width=1)
                    elif sf.kind == "sidewalk":
                        w = max(1, int(sf.width * 1.5))
                        draw.line(projected, fill=_POV_SIDEWALK, width=w)
                    elif sf.kind == "underground_utility":
                        draw.line(projected, fill=_POV_UTILITY, width=1)
                    else:
                        draw.line(projected, fill=_POV_FEATURE_PT, width=1)

            elif sf.geometry_type == "point" and sf.position:
                r = self._project(sf.position)
                if r:
                    px, py = int(r[0]), int(r[1])
                    if sf.kind in ("tree", "tree_cluster"):
                        # Draw trunk
                        trunk_top = self._project(
                            Point3D(sf.position.x, sf.position.y, sf.position.z + sf.height * 0.6))
                        canopy_center = self._project(
                            Point3D(sf.position.x, sf.position.y, sf.position.z + sf.height * 0.75))
                        if trunk_top and canopy_center:
                            tx, ty = int(trunk_top[0]), int(trunk_top[1])
                            cx, cy = int(canopy_center[0]), int(canopy_center[1])
                            # Trunk line
                            draw.line([(px, py), (tx, ty)], fill=_POV_TREE_TRUNK, width=2)
                            # Canopy circle (approximate size from depth)
                            canopy_px = max(4, int(sf.canopy_radius * 15 / max(1, r[2])))
                            draw.ellipse(
                                [cx - canopy_px, cy - canopy_px, cx + canopy_px, cy + canopy_px],
                                fill=_POV_TREE_CANOPY, outline=(25, 50, 35)
                            )
                    elif sf.kind in ("fire_hydrant", "manhole", "catch_basin"):
                        draw.ellipse([px-3, py-3, px+3, py+3], fill=(180, 50, 50), outline=(200, 70, 70))
                    elif sf.kind == "light_pole":
                        top = self._project(
                            Point3D(sf.position.x, sf.position.y, sf.position.z + sf.height))
                        if top:
                            draw.line([(px, py), (int(top[0]), int(top[1]))],
                                      fill=_POV_FEATURE_PT, width=2)
                            draw.ellipse([int(top[0])-4, int(top[1])-4,
                                          int(top[0])+4, int(top[1])+4],
                                         fill=(200, 200, 140))

    def _collect_wall_faces(self, faces: list, wall: Wall,
                            ox: float = 0, oy: float = 0, oz: float = 0) -> None:
        """Decompose a wall into front/top/side face quads with openings cut out."""
        z0 = wall.base_elevation + oz
        z1 = z0 + wall.height
        wl = wall.length
        if wl < 0.01:
            return

        sx, sy = wall.start.x + ox, wall.start.y + oy
        ex, ey = wall.end.x + ox, wall.end.y + oy
        dx = ex - sx
        dy = ey - sy
        ux, uy = dx / wl, dy / wl
        nx, ny = -uy * wall.thickness / 2, ux * wall.thickness / 2

        bl_o = Point3D(sx + nx, sy + ny, z0)
        br_o = Point3D(ex + nx, ey + ny, z0)
        tl_o = Point3D(sx + nx, sy + ny, z1)
        tr_o = Point3D(ex + nx, ey + ny, z1)

        bl_i = Point3D(sx - nx, sy - ny, z0)
        br_i = Point3D(ex - nx, ey - ny, z0)
        tl_i = Point3D(sx - nx, sy - ny, z1)
        tr_i = Point3D(ex - nx, ey - ny, z1)

        # Decide which face is "front" (facing camera) via dot product with view dir
        face_normal_outer = (nx, ny, 0)
        eye_to_wall = _v3_sub(
            Point3D((wall.start.x + wall.end.x) / 2, (wall.start.y + wall.end.y) / 2, (z0 + z1) / 2),
            Point3D(*self.eye),
        )
        dot_outer = _v3_dot(face_normal_outer, eye_to_wall)

        if dot_outer < 0:
            # Camera sees the outer face
            front_bl, front_br, front_tl, front_tr = bl_o, br_o, tl_o, tr_o
        else:
            # Camera sees the inner face
            front_bl, front_br, front_tl, front_tr = bl_i, br_i, tl_i, tr_i

        # Front face — full wall
        result = self._project_quad([front_bl, front_br, front_tr, front_tl])
        if result:
            faces.append((result[1], "wall_front", result[0], _POV_WALL_FRONT))

        # Top face
        result = self._project_quad([tl_o, tr_o, tr_i, tl_i])
        if result:
            faces.append((result[1] - 0.01, "wall_top", result[0], _POV_WALL_TOP))

        # Side faces (wall ends) — only the one facing the camera
        for side_pts in [[bl_o, bl_i, tl_i, tl_o], [br_i, br_o, tr_o, tr_i]]:
            mid = Point3D(
                sum(p.x for p in side_pts) / 4,
                sum(p.y for p in side_pts) / 4,
                sum(p.z for p in side_pts) / 4,
            )
            to_eye = _v3_sub(Point3D(*self.eye), mid)
            side_edge = _v3_sub(side_pts[1], side_pts[0])
            side_up = (0, 0, 1)
            side_n = _v3_cross(side_edge, side_up)
            if _v3_dot(side_n, to_eye) > 0:
                r = self._project_quad(side_pts)
                if r:
                    faces.append((r[1], "wall_side", r[0], _POV_WALL_SIDE))

        # Openings — rendered ON TOP of the wall face (closer depth)
        for op in wall.openings:
            t0 = op.offset_along_wall / wl
            t1 = (op.offset_along_wall + op.width) / wl
            oz_bot = z0 + op.sill_height
            oz_top = oz_bot + op.height

            if dot_outer < 0:
                o_bl = Point3D(bl_o.x + (br_o.x - bl_o.x) * t0, bl_o.y + (br_o.y - bl_o.y) * t0, oz_bot)
                o_br = Point3D(bl_o.x + (br_o.x - bl_o.x) * t1, bl_o.y + (br_o.y - bl_o.y) * t1, oz_bot)
                o_tr = Point3D(bl_o.x + (br_o.x - bl_o.x) * t1, bl_o.y + (br_o.y - bl_o.y) * t1, oz_top)
                o_tl = Point3D(bl_o.x + (br_o.x - bl_o.x) * t0, bl_o.y + (br_o.y - bl_o.y) * t0, oz_top)
            else:
                o_bl = Point3D(bl_i.x + (br_i.x - bl_i.x) * t0, bl_i.y + (br_i.y - bl_i.y) * t0, oz_bot)
                o_br = Point3D(bl_i.x + (br_i.x - bl_i.x) * t1, bl_i.y + (br_i.y - bl_i.y) * t1, oz_bot)
                o_tr = Point3D(bl_i.x + (br_i.x - bl_i.x) * t1, bl_i.y + (br_i.y - bl_i.y) * t1, oz_top)
                o_tl = Point3D(bl_i.x + (br_i.x - bl_i.x) * t0, bl_i.y + (br_i.y - bl_i.y) * t0, oz_top)

            r = self._project_quad([o_bl, o_br, o_tr, o_tl])
            if r:
                ftype = "window" if op.kind == OpeningKind.WINDOW else "door"
                faces.append((r[1] - 0.05, ftype, r[0], None))

    def _draw_overlay(self, draw: ImageDraw.Draw) -> None:
        """Draw title and viewpoint name overlay."""
        ft = _load_font(18)
        fs = _load_font(13)
        fn = _load_font(11)

        # Semi-transparent bar at top
        for y in range(50):
            alpha = max(0, 200 - y * 4)
            c = tuple(max(0, min(255, int(_POV_BG[i] * alpha / 255))) for i in range(3))
            draw.line([(0, y), (self.IMG_W, y)], fill=c)

        draw.text((20, 8), self.vp.name, fill=_POV_LABEL, font=ft)
        draw.text((20, 30), self.model.title, fill=_POV_DIM, font=fs)

        # Viewpoint info bottom-left
        info = f"eye=({self.vp.eye.x:.1f}, {self.vp.eye.y:.1f}, {self.vp.eye.z:.1f})  " \
               f"fov={self.vp.fov_deg:.0f}°  {self.vp.projection}"
        draw.text((20, self.IMG_H - 25), info, fill=_POV_DIM, font=fn)

        # Note in bottom-right if present
        if self.vp.note:
            note_text = self.vp.note[:100] + ("..." if len(self.vp.note) > 100 else "")
            bb = fn.getbbox(note_text)
            tw = bb[2] - bb[0]
            draw.text((self.IMG_W - tw - 20, self.IMG_H - 25), note_text, fill=_POV_DIM, font=fn)



process.stderr.write(
  `[dedup] $defs: ${Object.keys(sortedDefs).length}, ` +
    `aliases merged: ${aliasMap.size}, ` +
    `output: ${output.split("\n").length} lines / ${(output.length / 1024).toFixed(1)} KB ` +
    `(was ${(origSize / 1024).toFixed(1)} KB inlined)\n`,
);

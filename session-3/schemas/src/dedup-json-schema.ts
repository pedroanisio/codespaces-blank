/**
 * dedup-json-schema.ts — Post-processor that transforms the inlined zod-to-json-schema
 * output into a compact, $defs/$ref form.
 *
 * Adapted from session-02/schemas/ts/dedup-json-schema.ts (13-pass pipeline).
 *
 * Usage: npx tsx src/dedup-json-schema.ts > active/human-body-v3.schema.json
 *
 * Improvements over raw zod-to-json-schema output:
 *   1. Extracts shared types into $defs and replaces with $ref
 *   2. Strips JS safe-integer bounds (±9007199254740991) from z.number().int()
 *   3. Strips redundant Zod datetime regex patterns (format: date-time suffices)
 *   4. Merges alias definitions (same fingerprint, different name)
 *   5. Removes pass-through and unreferenced $defs
 *   6. Migrates definitions → $defs (draft 2020-12 convention)
 *
 * Generated by: Claude Opus 4.6 (1M context)
 */

import { zodToJsonSchema } from "zod-to-json-schema";
import { z } from "zod";
import * as schemaModule from "./index.js";
import { HumanBodySchema } from "./body.js";

// ═════════════════════════════════════════════════════════════════════════════
// §1  CONFIGURATION
// ═════════════════════════════════════════════════════════════════════════════

// Schemas to skip (root-level or non-convertible)
const SKIP_EXPORTS = new Set([
  "HumanBodySchema",
  // Branded ID helpers are just uuid strings — no need for individual defs
  "BoneId", "MuscleId", "JointId", "OrganId", "VesselId", "NerveId",
  "TendonId", "ClothingId", "SegmentId", "PoseId", "ForceId",
  "MomentId", "LoadingConditionId", "ContactId",
  // Version constants and non-schema exports
  "SCHEMA_VERSION", "DERIVATION_GRAPH_VERSION", "CONSTITUTIVE_LAWS_VERSION",
  "CSG_MAX_NODE_COUNT", "CSG_MAX_DEPTH",
  "STANDARD_VALIDITY_BOUNDARIES",
  "countCSGNodes", "csgTreeDepth",
]);

// JS safe integer bounds emitted by Zod for z.number().int()
const JS_SAFE_INT_MAX = 9007199254740991;
const JS_SAFE_INT_MIN = -9007199254740991;

// Minimum fingerprint length to be worth extracting as a $def
const INLINE_THRESHOLD = 40;

// ═════════════════════════════════════════════════════════════════════════════
// §2  GENERATE INDIVIDUAL JSON SCHEMAS
// ═════════════════════════════════════════════════════════════════════════════

interface DefEntry {
  name: string;
  schema: any;
}

const entries: DefEntry[] = [];

for (const [exportName, value] of Object.entries(schemaModule)) {
  if (SKIP_EXPORTS.has(exportName)) continue;
  if (!exportName.endsWith("Schema") && !exportName.endsWith("Enum")) continue;
  if (!(value instanceof z.ZodType)) continue;

  // Derive a clean def name: "BoneSchema" → "Bone", "SexEnum" → "Sex"
  const defName = exportName
    .replace(/Schema$/, "")
    .replace(/Enum$/, "");

  try {
    const js = zodToJsonSchema(value, {
      $refStrategy: "none",
      target: "jsonSchema2019-09",
    });
    // Remove top-level wrappers that zod-to-json-schema adds
    delete (js as any).$schema;
    delete (js as any).$ref;
    entries.push({ name: defName, schema: js });
  } catch {
    // skip unconvertible (recursive types etc.)
  }
}

process.stderr.write(`[dedup] Generated ${entries.length} individual JSON Schemas\n`);

// ═════════════════════════════════════════════════════════════════════════════
// §3  FINGERPRINTING AND DEDUP MAP
// ═════════════════════════════════════════════════════════════════════════════

function canonicalize(obj: unknown): string {
  if (obj === null || obj === undefined) return String(obj);
  if (typeof obj !== "object") return JSON.stringify(obj);
  if (Array.isArray(obj)) {
    return "[" + obj.map(canonicalize).join(",") + "]";
  }
  const sorted = Object.keys(obj as any).sort();
  return (
    "{" +
    sorted
      .map((k) => JSON.stringify(k) + ":" + canonicalize((obj as any)[k]))
      .join(",") +
    "}"
  );
}

// Sort: largest first for priority matching
entries.sort(
  (a, b) => canonicalize(b.schema).length - canonicalize(a.schema).length,
);

const fpToDef = new Map<string, string>();
const defs: Record<string, any> = {};

for (const entry of entries) {
  const fp = canonicalize(entry.schema);
  if (fp.length < INLINE_THRESHOLD) continue;
  if (!fpToDef.has(fp)) {
    fpToDef.set(fp, entry.name);
  }
  defs[entry.name] = JSON.parse(JSON.stringify(entry.schema));
}

process.stderr.write(`[dedup] ${Object.keys(defs).length} definitions in dedup map\n`);

// ═════════════════════════════════════════════════════════════════════════════
// §4  STRIP ZOD ARTIFACTS
// ═════════════════════════════════════════════════════════════════════════════

/**
 * Walk any JSON value and:
 *   - Remove minimum/maximum that equal ±MAX_SAFE_INTEGER (Zod .int() artifact)
 *   - Remove redundant datetime regex patterns when format: date-time is present
 */
function stripZodArtifacts(node: unknown): unknown {
  if (node === null || node === undefined || typeof node !== "object") return node;
  if (Array.isArray(node)) return node.map(stripZodArtifacts);

  const obj = node as Record<string, unknown>;
  const result: Record<string, unknown> = {};

  for (const [key, val] of Object.entries(obj)) {
    result[key] = stripZodArtifacts(val);
  }

  // Strip safe-int bounds on integers
  if (result.type === "integer") {
    if (result.minimum === JS_SAFE_INT_MIN) delete result.minimum;
    if (result.maximum === JS_SAFE_INT_MAX) delete result.maximum;
  }

  // Strip Zod datetime mega-pattern when format: date-time is present
  if (
    result.format === "date-time" &&
    typeof result.pattern === "string" &&
    (result.pattern as string).length > 50
  ) {
    delete result.pattern;
  }

  return result;
}

// Apply to all defs
for (const [defName, defSchema] of Object.entries(defs)) {
  defs[defName] = stripZodArtifacts(defSchema);
}

// ═════════════════════════════════════════════════════════════════════════════
// §5  SUBTREE REPLACEMENT ($ref)
// ═════════════════════════════════════════════════════════════════════════════

// Rebuild fingerprint map after stripping artifacts
fpToDef.clear();
for (const entry of entries) {
  const stripped = stripZodArtifacts(entry.schema) as Record<string, unknown>;
  const fp = canonicalize(stripped);
  if (fp.length < INLINE_THRESHOLD) continue;
  if (!fpToDef.has(fp)) {
    fpToDef.set(fp, entry.name);
  }
}

function replaceSubtrees(
  node: unknown,
  skipRoot: boolean = false,
): unknown {
  if (node === null || node === undefined || typeof node !== "object") return node;
  if (Array.isArray(node)) return node.map((item) => replaceSubtrees(item));

  const obj = node as Record<string, unknown>;
  if (obj.$ref) return obj;

  if (!skipRoot) {
    const fp = canonicalize(obj);
    const defName = fpToDef.get(fp);
    if (defName && fp.length >= INLINE_THRESHOLD) {
      return { $ref: `#/$defs/${defName}` };
    }
  }

  const result: Record<string, unknown> = {};
  for (const [key, val] of Object.entries(obj)) {
    result[key] = replaceSubtrees(val);
  }
  return result;
}

// Iterative dedup passes
for (let pass = 0; pass < 10; pass++) {
  let changes = 0;
  for (const [defName, defSchema] of Object.entries(defs)) {
    const before = canonicalize(defSchema);
    const after = replaceSubtrees(defSchema, true);
    if (before !== canonicalize(after)) {
      defs[defName] = after;
      changes++;
    }
  }
  if (changes === 0) {
    process.stderr.write(
      `[dedup] Subtree replacement stabilized after ${pass + 1} pass(es)\n`,
    );
    break;
  }
}

// ═════════════════════════════════════════════════════════════════════════════
// §6  REGISTER SHARED PRIMITIVES AS $defs
// ═════════════════════════════════════════════════════════════════════════════

// Ensure key shared types are registered as defs even if they didn't
// meet the inline threshold during initial collection.

const SHARED_TYPES: Array<{ name: string; schema: z.ZodType }> = [
  { name: "Vector3", schema: schemaModule.Vector3Schema },
  { name: "Quaternion", schema: schemaModule.QuaternionSchema },
  { name: "RigidPose", schema: schemaModule.RigidPoseSchema },
  { name: "SymmetricTensor3", schema: schemaModule.SymmetricTensor3Schema },
  { name: "Color", schema: schemaModule.ColorSchema },
  { name: "Transform", schema: schemaModule.TransformSchema },
];

for (const { name, schema } of SHARED_TYPES) {
  if (!defs[name]) {
    try {
      const js = zodToJsonSchema(schema, {
        $refStrategy: "none",
        target: "jsonSchema2019-09",
      });
      delete (js as any).$schema;
      delete (js as any).$ref;
      const stripped = stripZodArtifacts(js);
      defs[name] = stripped;
      fpToDef.set(canonicalize(stripped), name);
    } catch { /* skip */ }
  }
}

// Extensions = record<string, unknown> → additionalProperties: true
if (!defs["Extensions"]) {
  defs["Extensions"] = {
    type: "object",
    additionalProperties: {},
  };
  fpToDef.set(canonicalize(defs["Extensions"]), "Extensions");
}

// Run another dedup pass to replace shared-type inline occurrences
for (let pass = 0; pass < 5; pass++) {
  let changes = 0;
  for (const [defName, defSchema] of Object.entries(defs)) {
    if (SHARED_TYPES.some((s) => s.name === defName) || defName === "Extensions") continue;
    const before = canonicalize(defSchema);
    const after = replaceSubtrees(defSchema, true);
    if (before !== canonicalize(after)) {
      defs[defName] = after;
      changes++;
    }
  }
  if (changes === 0) break;
}

// ═════════════════════════════════════════════════════════════════════════════
// §7  ALIAS MERGING AND CLEANUP
// ═════════════════════════════════════════════════════════════════════════════

// Remove duplicate defs (same fingerprint, different name)
const fpToCanonicalName = new Map<string, string>();
const aliasMap = new Map<string, string>();

for (const [defName, defSchema] of Object.entries(defs)) {
  const fp = canonicalize(defSchema);
  const existing = fpToCanonicalName.get(fp);
  if (existing && existing !== defName) {
    aliasMap.set(defName, existing);
  } else {
    fpToCanonicalName.set(fp, defName);
  }
}

for (const alias of aliasMap.keys()) {
  delete defs[alias];
}

function rewriteAliases(node: unknown): unknown {
  if (node === null || node === undefined || typeof node !== "object") return node;
  if (Array.isArray(node)) return node.map(rewriteAliases);
  const obj = node as Record<string, unknown>;
  if (typeof obj.$ref === "string") {
    const refName = (obj.$ref as string).replace("#/$defs/", "");
    const canonical = aliasMap.get(refName);
    if (canonical) return { $ref: `#/$defs/${canonical}` };
    return obj;
  }
  const result: Record<string, unknown> = {};
  for (const [key, val] of Object.entries(obj)) {
    result[key] = rewriteAliases(val);
  }
  return result;
}

for (const [defName, defSchema] of Object.entries(defs)) {
  defs[defName] = rewriteAliases(defSchema);
}

if (aliasMap.size > 0) {
  process.stderr.write(`[dedup] Merged ${aliasMap.size} alias(es)\n`);
}

// ═════════════════════════════════════════════════════════════════════════════
// §8  BUILD ROOT SCHEMA
// ═════════════════════════════════════════════════════════════════════════════

const fullInlined = zodToJsonSchema(HumanBodySchema, {
  $refStrategy: "root",
  target: "jsonSchema2019-09",
}) as Record<string, unknown>;

// Flatten: zod-to-json-schema wraps in { definitions: { HumanBody: {...} }, $ref: "..." }
let rootBody: Record<string, unknown>;
if (fullInlined.definitions && (fullInlined.definitions as any).HumanBody) {
  rootBody = (fullInlined.definitions as any).HumanBody;

  // Merge library-generated definitions into our defs (these handle recursion etc.)
  const libDefs = fullInlined.definitions as Record<string, any>;
  for (const [name, schema] of Object.entries(libDefs)) {
    if (name === "HumanBody") continue;
    if (!defs[name]) {
      defs[name] = stripZodArtifacts(schema);
    }
  }
} else {
  rootBody = fullInlined;
}

// Inline-expand any #/definitions/ refs in the root that point to our $defs,
// so our fingerprint-based dedup can match them
function inlineLibRefs(node: unknown): unknown {
  if (node === null || node === undefined || typeof node !== "object") return node;
  if (Array.isArray(node)) return node.map(inlineLibRefs);
  const obj = node as Record<string, unknown>;
  if (typeof obj.$ref === "string") {
    const refPath = obj.$ref as string;
    const defName = refPath.replace("#/definitions/", "");
    // If we have this def, inline it so fingerprinting works on the root
    if (defs[defName] && !JSON.stringify(defs[defName]).includes(refPath)) {
      return JSON.parse(JSON.stringify(defs[defName]));
    }
    return obj;
  }
  const result: Record<string, unknown> = {};
  for (const [key, val] of Object.entries(obj)) {
    result[key] = inlineLibRefs(val);
  }
  return result;
}

// Selectively inline non-recursive refs so fingerprinting works
rootBody = inlineLibRefs(rootBody) as Record<string, unknown>;

const rootCleaned = stripZodArtifacts(rootBody) as Record<string, unknown>;
const rootDeduped = replaceSubtrees(rootCleaned, true) as Record<string, unknown>;
const rootFinal = rewriteAliases(rootDeduped) as Record<string, unknown>;

// ═════════════════════════════════════════════════════════════════════════════
// §9  MIGRATE definitions → $defs (draft 2020-12)
// ═════════════════════════════════════════════════════════════════════════════

// zod-to-json-schema uses "definitions" (draft-07 convention). We migrate all
// $ref pointers from #/definitions/ to #/$defs/ for draft 2020-12 compliance.

function migrateRefs(node: unknown): unknown {
  if (node === null || node === undefined || typeof node !== "object") return node;
  if (Array.isArray(node)) return node.map(migrateRefs);
  const obj = node as Record<string, unknown>;
  if (typeof obj.$ref === "string") {
    return { $ref: (obj.$ref as string).replace("#/definitions/", "#/$defs/") };
  }
  const result: Record<string, unknown> = {};
  for (const [key, val] of Object.entries(obj)) {
    result[key] = migrateRefs(val);
  }
  return result;
}

for (const [defName, defSchema] of Object.entries(defs)) {
  defs[defName] = migrateRefs(defSchema);
}

// ═════════════════════════════════════════════════════════════════════════════
// §10  CLEAN UP PASS-THROUGH AND UNREFERENCED $defs
// ═════════════════════════════════════════════════════════════════════════════

// Remove defs that are just a $ref to another def (pass-through)
for (const [defName, defSchema] of Object.entries(defs)) {
  if (defSchema.$ref && Object.keys(defSchema).length === 1) {
    const target = defSchema.$ref;
    const refStr = `#/$defs/${defName}`;
    const replaceRef = (node: unknown): unknown => {
      if (node === null || node === undefined || typeof node !== "object") return node;
      if (Array.isArray(node)) return node.map(replaceRef);
      const obj = node as Record<string, unknown>;
      if (obj.$ref === refStr) return { $ref: target };
      const result: Record<string, unknown> = {};
      for (const [k, v] of Object.entries(obj)) {
        result[k] = replaceRef(v);
      }
      return result;
    };
    Object.assign(rootFinal, replaceRef(rootFinal));
    for (const [otherName, otherSchema] of Object.entries(defs)) {
      if (otherName !== defName) defs[otherName] = replaceRef(otherSchema);
    }
    delete defs[defName];
  }
}

// Remove unreferenced defs
function collectRefs(node: unknown, refs: Set<string>): void {
  if (node === null || node === undefined || typeof node !== "object") return;
  if (Array.isArray(node)) {
    node.forEach((n) => collectRefs(n, refs));
    return;
  }
  const obj = node as Record<string, unknown>;
  if (typeof obj.$ref === "string") {
    refs.add((obj.$ref as string).replace("#/$defs/", ""));
  }
  for (const val of Object.values(obj)) collectRefs(val, refs);
}

for (let i = 0; i < 10; i++) {
  const usedRefs = new Set<string>();
  collectRefs(rootFinal, usedRefs);
  for (const defSchema of Object.values(defs)) collectRefs(defSchema, usedRefs);

  let removed = 0;
  for (const defName of Object.keys(defs)) {
    if (!usedRefs.has(defName)) {
      delete defs[defName];
      removed++;
    }
  }
  if (removed === 0) break;
  process.stderr.write(`[dedup] Removed ${removed} unreferenced def(s)\n`);
}

// ═════════════════════════════════════════════════════════════════════════════
// §11  ASSEMBLE AND OUTPUT
// ═════════════════════════════════════════════════════════════════════════════

const final: Record<string, unknown> = {
  $schema: "https://json-schema.org/draft/2020-12/schema",
  $id: "https://example.org/schemas/human-body-v3.schema.json",
  title: "Human Body Schema",
  description:
    "Comprehensive anatomical data schema for human body modeling. " +
    "Covers skeletal, muscular, connective, nervous, vascular, organ, " +
    "appearance, kinematics, dynamics, derivation, constitutive, and geometry subsystems. " +
    "Generated from Zod v3 TypeScript source via dedup post-processor. Schema version 3.0.0.",
};

for (const [key, val] of Object.entries(rootFinal as Record<string, unknown>)) {
  if (key === "$schema" || key === "$id" || key === "title" || key === "description") continue;
  final[key] = migrateRefs(val);
}

const sortedDefs: Record<string, any> = {};
for (const key of Object.keys(defs).sort()) {
  sortedDefs[key] = defs[key];
}
final.$defs = sortedDefs;

const output = JSON.stringify(final, null, 2);
console.log(output);


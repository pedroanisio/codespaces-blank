export type GroundReactionForce = z.infer<typeof GroundReactionForceSchema>;
export type JointReactionForce = z.infer<typeof JointReactionForceSchema>;
export type ExternalForce = z.infer<typeof ExternalForceSchema>;
export type LigamentousForce = z.infer<typeof LigamentousForceSchema>;
export type InertialForce = z.infer<typeof InertialForceSchema>;
export type ContactForce = z.infer<typeof ContactForceSchema>;
export type AerodynamicDrag = z.infer<typeof AerodynamicDragSchema>;
export type BuoyancyForce = z.infer<typeof BuoyancyForceSchema>;
export type Moment = z.infer<typeof MomentSchema>;
export type Contact = z.infer<typeof ContactSchema>;
export type LoadingCondition = z.infer<typeof LoadingConditionSchema>;
export type FreeBodyDiagram = z.infer<typeof FreeBodyDiagramSchema>;

export const ConstitutiveLawSchema = z.discriminatedUnion("lawType", [
  HillMuscleLawSchema,
  LigamentForceStrainLawSchema,
  CartilageStressStrainLawSchema,
  BoneYieldCriterionSchema,
  JointRangeLimitSchema,
]);

// =============================================================================
// Constitutive Laws Collection
//
// The complete set of constitutive laws for a body model. Analogous to
// DerivationGraph but for inequality/envelope constraints rather than
// functional derivations.
//
// Design: ConstitutiveLaws + DerivationGraph together form C5 (Physical
// Consistency Validator) from the step-change contribution analysis.
// =============================================================================

export const ConstitutiveLawsSchema = z
  .object({
    version: z.literal(CONSTITUTIVE_LAWS_VERSION),
    laws: z.array(ConstitutiveLawSchema).min(1),
  })
  .superRefine((collection, ctx) => {
    // Validate unique IDs across all laws
    const ids = new Set<string>();
    collection.laws.forEach((law, i) => {
      if (ids.has(law.id)) {
        ctx.addIssue({
          code: z.ZodIssueCode.custom,
          message: `Duplicate constitutive law ID: ${law.id}`,
          path: ["laws", i, "id"],
        });
      }
      ids.add(law.id);
    });
  });


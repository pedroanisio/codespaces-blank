// Standard Validity Boundaries for the Rigid Body Model (G3)
//
// These are not schema entities — they are reference constants that
// consumers can use when instantiating constitutive laws. Provided
// here as documentation-in-code.
// =============================================================================

export const STANDARD_VALIDITY_BOUNDARIES = {
  rigidBody: {
    assumption: "Bones are rigid bodies",
    validWhen: "Bone stress << yield stress; strain rate < 0.01/s; no fracture or plastic deformation",
    violatedWhen: "Impact loading (strain rate > 1/s), stress approaching yield (~130 MPa cortical), pathological bone (osteoporosis)",
    consequence: "Rigid body dynamics underestimates deformation and energy absorption; joint forces may be overestimated",
    reference: "Reilly & Burstein, J Bone Joint Surg Am 56(5):1001–1022, 1974",
  },
  perfectConstraints: {
    assumption: "Joints are ideal kinematic constraints (no laxity, no deformation)",
    validWhen: "Joint loads within normal physiological range; intact ligaments; healthy cartilage",
    violatedWhen: "Ligament rupture, joint subluxation, large arthroplasty clearances, pathological laxity",
    consequence: "Joint kinematics deviate from the model; actual ROM may exceed modeled limits; contact mechanics are wrong",
    reference: "Woo et al., Am J Sports Med 27(4):533–543, 1999",
  },
  rigidSegments: {
    assumption: "Body segments are rigid (soft tissue wobble mass ignored)",
    validWhen: "Slow to moderate movements; low-impact activities (walking, cycling, lifting)",
    violatedWhen: "High-impact landing (> 3× body weight GRF), sprinting, explosive jumping — soft tissue deforms and oscillates",
    consequence: "Peak forces underestimated by 10–30%; inverse dynamics joint moments less accurate",
    reference: "Pain & Challis, J Appl Biomech 22(3):224–232, 2006",
  },
  quasiStatic: {
    assumption: "Loading is quasi-static (inertial effects negligible)",
    validWhen: "Movement duration >> natural period of the body segment; acceleration << g",
    violatedWhen: "Impact, vibration, rapid voluntary movements with segment accelerations > 2g",
    consequence: "Static equilibrium analysis gives wrong joint forces; must use full dynamic equations",
    reference: "Winter, 'Biomechanics and Motor Control of Human Movement', 4th ed. (2009), Ch. 4",
  },
} as const;


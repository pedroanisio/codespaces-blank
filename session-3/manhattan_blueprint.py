@dataclass
class Space:
    id: str
    floor_id: str
    name: str
    usage: SpaceUsage
    boundary: BoundaryWithHoles2D
    floor_elevation: float      # Z of finished floor
    ceiling_elevation: float    # Z of finished ceiling
    area_sq_units: Optional[float] = None
    volume_cu_units: Optional[float] = None
    finish_floor: Optional[str] = None

    def computed_area(self) -> float:
        if self.area_sq_units is not None:
            return self.area_sq_units
        return _polygon_area(self.boundary.outer)

    def room_height(self) -> float:
        return self.ceiling_elevation - self.floor_elevation

    def centroid(self) -> Point2D:
        verts = self.boundary.outer.vertices
        return Point2D(
            sum(v.x for v in verts) / len(verts),
            sum(v.y for v in verts) / len(verts),
        )

    def bounding_box(self) -> tuple[float, float, float, float]:
        verts = self.boundary.outer.vertices
        xs = [v.x for v in verts]; ys = [v.y for v in verts]
        return min(xs), min(ys), max(xs), max(ys)


def _polygon_area(poly: Polygon2D) -> float:
    verts = poly.vertices; n = len(verts); area = 0.0
    for i in range(n):
        j = (i + 1) % n
        area += verts[i].x * verts[j].y - verts[j].x * verts[i].y
    return abs(area) / 2.0



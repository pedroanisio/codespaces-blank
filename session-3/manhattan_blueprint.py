def _make_model(title: str, building_name: str, spaces_def: list[tuple],
                note: str = "",
                window_sides: set[str] | None = None) -> BuildingModel:
    """Generic builder: takes a list of (name, usage, x, y, w, h) tuples."""
    bid, fid = _uuid(), _uuid()
    spaces = [_rect_space(fid, n, u, x, y, w, h) for n, u, x, y, w, h in spaces_def]
    interior_walls = _derive_walls(fid, spaces)
    exterior_walls = _derive_exterior_walls(fid, spaces, window_sides=window_sides)
    slab = _floor_slab(fid, spaces)
    floor = Floor(id=fid, building_id=bid, level=0, name="Floor Plan",
                  elevation_above_datum=0, floor_to_floor_height=FLOOR_TO_FLOOR,
                  spaces=spaces, walls=interior_walls + exterior_walls, slabs=[slab])
    return BuildingModel(
        schema_version=SCHEMA_VERSION, id=_uuid(), title=title,
        length_unit=LengthUnit.M,
        building=Building(id=bid, name=building_name, typology="residential apartment"),
        floors=[floor], metadata=_meta(note),
    )



WALL_HEIGHT = 2.7       # standard apartment wall height
SLAB_THICKNESS = 0.2    # floor slab thickness
FLOOR_TO_FLOOR = 3.0    # floor-to-floor height


def _rect_space(fid: str, name: str, usage: SpaceUsage,
                x: float, y: float, w: float, h: float,
                z: float = 0.0) -> Space:
    return Space(
        id=_uuid(), floor_id=fid, name=name, usage=usage,
        boundary=BoundaryWithHoles2D(outer=Polygon2D([
            Point2D(x,y), Point2D(x+w,y), Point2D(x+w,y+h), Point2D(x,y+h),
        ])),
        floor_elevation=z,
        ceiling_elevation=z + WALL_HEIGHT,
        area_sq_units=w * h,
        volume_cu_units=w * h * WALL_HEIGHT,
    )


def _rect_wall(fid: str, x0: float, y0: float, x1: float, y1: float,
               z: float = 0.0, *, openings: list[Opening] | None = None) -> Wall:
    return Wall(
        id=_uuid(), floor_id=fid, wall_type=WallType.PARTITION,
        start=Point2D(x0, y0), end=Point2D(x1, y1),
        thickness=0.15, height=WALL_HEIGHT, base_elevation=z,
        openings=openings or [],
    )


def _door(offset: float, width: float = 0.9) -> Opening:
    return Opening(id=_uuid(), kind=OpeningKind.SINGLE_DOOR,
                   offset_along_wall=offset, width=width,
                   height=2.1, sill_height=0.0,
                   swing_direction=SwingDirection.INWARD_RIGHT)


def _window(offset: float, width: float = 1.2, height: float = 1.4,
            sill: float = 0.9) -> Opening:
    """Create a window opening. Default sill at 0.9m, 1.4m tall, 1.2m wide."""
    return Opening(id=_uuid(), kind=OpeningKind.WINDOW,
                   offset_along_wall=offset, width=width,
                   height=height, sill_height=sill,
                   swing_direction=SwingDirection.NONE)


_NO_DOOR = {SpaceUsage.CLOSET, SpaceUsage.STORAGE}


def _derive_walls(fid: str, spaces: list[Space], z: float = 0.0) -> list[Wall]:
    """Derive interior walls with doors from adjacent rectangular spaces."""
    EPS = 0.05

    @dataclass
    class Edge:
        x0: float; y0: float; x1: float; y1: float
        idx: int; horiz: bool

    edges: list[Edge] = []
    for i, sp in enumerate(spaces):
        bb = sp.bounding_box(); sx0, sy0, sx1, sy1 = bb
        edges += [Edge(sx0,sy0,sx1,sy0,i,True), Edge(sx0,sy1,sx1,sy1,i,True),
                  Edge(sx0,sy0,sx0,sy1,i,False), Edge(sx1,sy0,sx1,sy1,i,False)]

    walls: list[Wall] = []; seen: set[tuple[int,int]] = set()
    for e1 in edges:
        for e2 in edges:
            if e1.idx >= e2.idx or e1.horiz != e2.horiz: continue
            pair = (e1.idx, e2.idx)
            if pair in seen: continue
            if e1.horiz:
                if abs(e1.y0 - e2.y0) > EPS: continue
                os, oe = max(e1.x0,e2.x0), min(e1.x1,e2.x1)
                if oe - os < EPS: continue
                seen.add(pair); wl = oe - os
                ops = []
                if spaces[e1.idx].usage not in _NO_DOOR and spaces[e2.idx].usage not in _NO_DOOR and wl >= 1.0:
                    dw = min(0.9, wl*0.6); ops.append(_door((wl-dw)/2, dw))
                walls.append(_rect_wall(fid, os, e1.y0, oe, e1.y0, z, openings=ops))
            else:
                if abs(e1.x0 - e2.x0) > EPS: continue
                os, oe = max(e1.y0,e2.y0), min(e1.y1,e2.y1)
                if oe - os < EPS: continue
                seen.add(pair); wl = oe - os
                ops = []
                if spaces[e1.idx].usage not in _NO_DOOR and spaces[e2.idx].usage not in _NO_DOOR and wl >= 1.0:
                    dw = min(0.9, wl*0.6); ops.append(_door((wl-dw)/2, dw))
                walls.append(_rect_wall(fid, e1.x0, os, e1.x0, oe, z, openings=ops))
    return walls


def _derive_exterior_walls(fid: str, spaces: list[Space], z: float = 0.0,
                            window_sides: set[str] | None = None) -> list[Wall]:
    """Create exterior (perimeter) walls with windows on specified sides.

    window_sides: subset of {"north", "south", "east", "west"} indicating
    which exterior walls get windows. Defaults to all sides.
    """
    if window_sides is None:
        window_sides = {"north", "south", "east", "west"}

    # Overall bounding box
    min_x = min_y = float("inf"); max_x = max_y = float("-inf")
    for sp in spaces:
        bb = sp.bounding_box()
        min_x = min(min_x, bb[0]); min_y = min(min_y, bb[1])
        max_x = max(max_x, bb[2]); max_y = max(max_y, bb[3])

    w = max_x - min_x; h = max_y - min_y
    ext_walls: list[Wall] = []

    def _wins(length: float) -> list[Opening]:
        """Place evenly-spaced windows along a wall."""
        win_w = 1.2
        spacing = 2.5  # center-to-center
        count = max(1, int((length - 1.0) / spacing))
        total = count * win_w + (count - 1) * (spacing - win_w)
        start = (length - total) / 2
        wins = []
        for i in range(count):
            offset = start + i * spacing
            if offset + win_w <= length + 0.01:
                wins.append(_window(offset, win_w))
        return wins

    # South wall (y = min_y, runs east)
    south_ops = _wins(w) if "south" in window_sides else []
    ext_walls.append(Wall(
        id=_uuid(), floor_id=fid, wall_type=WallType.LOAD_BEARING,
        start=Point2D(min_x, min_y), end=Point2D(max_x, min_y),
        thickness=0.25, height=WALL_HEIGHT, base_elevation=z,
        layer=LayerKind.EXTERIOR_ENVELOPE, openings=south_ops,
    ))
    # North wall (y = max_y, runs east)
    north_ops = _wins(w) if "north" in window_sides else []
    ext_walls.append(Wall(
        id=_uuid(), floor_id=fid, wall_type=WallType.LOAD_BEARING,
        start=Point2D(min_x, max_y), end=Point2D(max_x, max_y),
        thickness=0.25, height=WALL_HEIGHT, base_elevation=z,
        layer=LayerKind.EXTERIOR_ENVELOPE, openings=north_ops,
    ))
    # West wall (x = min_x, runs north)
    west_ops = _wins(h) if "west" in window_sides else []
    ext_walls.append(Wall(
        id=_uuid(), floor_id=fid, wall_type=WallType.LOAD_BEARING,
        start=Point2D(min_x, min_y), end=Point2D(min_x, max_y),
        thickness=0.25, height=WALL_HEIGHT, base_elevation=z,
        layer=LayerKind.EXTERIOR_ENVELOPE, openings=west_ops,
    ))
    # East wall (x = max_x, runs north)
    east_ops = _wins(h) if "east" in window_sides else []
    ext_walls.append(Wall(
        id=_uuid(), floor_id=fid, wall_type=WallType.LOAD_BEARING,
        start=Point2D(max_x, min_y), end=Point2D(max_x, max_y),
        thickness=0.25, height=WALL_HEIGHT, base_elevation=z,
        layer=LayerKind.EXTERIOR_ENVELOPE, openings=east_ops,
    ))
    return ext_walls


def _floor_slab(fid: str, spaces: list[Space], z: float = 0.0) -> Slab:
    """Create a floor slab covering all spaces."""
    min_x = min_y = float("inf"); max_x = max_y = float("-inf")
    for sp in spaces:
        bb = sp.bounding_box()
        min_x = min(min_x, bb[0]); min_y = min(min_y, bb[1])
        max_x = max(max_x, bb[2]); max_y = max(max_y, bb[3])
    return Slab(
        id=_uuid(), floor_id=fid, kind=SlabKind.FLOOR,
        boundary=BoundaryWithHoles2D(outer=Polygon2D([
            Point2D(min_x, min_y), Point2D(max_x, min_y),
            Point2D(max_x, max_y), Point2D(min_x, max_y),
        ])),
        thickness=SLAB_THICKNESS, elevation=z,
    )



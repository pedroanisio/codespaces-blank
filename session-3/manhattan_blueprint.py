class Severity(Enum):
    ERROR = "error"
    WARNING = "warning"

@dataclass
class ValidationFinding:
    severity: Severity
    entity_id: str
    rule: str
    message: str

    def __str__(self) -> str:
        icon = "✗" if self.severity == Severity.ERROR else "⚠"
        return f"  {icon} [{self.entity_id}] {self.rule}: {self.message}"


def _rects_overlap(a: tuple[float,float,float,float],
                   b: tuple[float,float,float,float], eps: float = 0.05) -> bool:
    """Check if two axis-aligned rects (min_x, min_y, max_x, max_y) overlap interior."""
    return (a[0] + eps < b[2] and b[0] + eps < a[2]
            and a[1] + eps < b[3] and b[1] + eps < a[3])


def validate_model(model: BuildingModel) -> list[ValidationFinding]:
    """Validate a BuildingModel for structural impossibilities.

    Categories:
      G — Geometry: degenerate shapes, negative dimensions
      O — Openings: exceed wall, overlap, float above wall
      S — Spaces: overlapping rooms, inverted elevations
      F — Floors: elevation consistency, missing elements
      W — Walls: zero-length, excessive thickness, unsupported spans
    """
    findings: list[ValidationFinding] = []

    def err(eid: str, rule: str, msg: str) -> None:
        findings.append(ValidationFinding(Severity.ERROR, eid, rule, msg))

    def warn(eid: str, rule: str, msg: str) -> None:
        findings.append(ValidationFinding(Severity.WARNING, eid, rule, msg))

    if not model.floors:
        err(model.id, "F-01", "BuildingModel has no floors")
        return findings

    # ── Floor-level checks ──────────────────────────────────────────────
    sorted_floors = sorted(model.floors, key=lambda f: f.level)
    for i, floor in enumerate(sorted_floors):
        fid = f"floor[{floor.level}]"

        # F-01: floor-to-floor height must be positive and reasonable
        if floor.floor_to_floor_height <= 0:
            err(fid, "F-01", f"floor_to_floor_height={floor.floor_to_floor_height} ≤ 0")
        elif floor.floor_to_floor_height > 10:
            warn(fid, "F-01", f"floor_to_floor_height={floor.floor_to_floor_height}m exceeds 10m — verify")

        # F-02: elevation continuity between consecutive floors
        if i > 0:
            prev = sorted_floors[i - 1]
            expected = prev.elevation_above_datum + prev.floor_to_floor_height
            gap = abs(floor.elevation_above_datum - expected)
            if gap > 0.01:
                warn(fid, "F-02",
                     f"Elevation gap: expected {expected:.2f}m "
                     f"(prev {prev.elevation_above_datum:.2f} + {prev.floor_to_floor_height:.2f}), "
                     f"got {floor.elevation_above_datum:.2f}m (gap={gap:.2f}m)")

        # F-03: floor must have at least one space
        if not floor.spaces:
            warn(fid, "F-03", "Floor has no spaces defined")

        # ── Wall checks ─────────────────────────────────────────────────
        for wall in floor.walls:
            wid = f"wall:{wall.id[:8]}"

            # W-01: zero-length wall
            if wall.length < 0.01:
                err(wid, "W-01", "Wall has zero/near-zero length")
                continue

            # W-02: wall thickness ratio — thickness > length is structurally absurd
            if wall.thickness >= wall.length:
                err(wid, "W-02",
                    f"Thickness ({wall.thickness:.2f}m) ≥ length ({wall.length:.2f}m)")

            # W-03: wall height must be positive and ≤ floor-to-floor
            if wall.height <= 0:
                err(wid, "W-03", f"Wall height={wall.height}m ≤ 0")
            elif wall.height > floor.floor_to_floor_height + 0.01:
                warn(wid, "W-03",
                     f"Wall height ({wall.height:.2f}m) exceeds "
                     f"floor-to-floor ({floor.floor_to_floor_height:.2f}m)")

            # W-04: wall thickness sanity
            if wall.thickness <= 0:
                err(wid, "W-04", f"Wall thickness={wall.thickness}m ≤ 0")
            elif wall.thickness > 1.0:
                warn(wid, "W-04", f"Wall thickness={wall.thickness}m exceeds 1m — verify")

            # W-05: wall base elevation should be near the floor elevation
            elev_diff = abs(wall.base_elevation - floor.elevation_above_datum)
            if elev_diff > floor.floor_to_floor_height:
                err(wid, "W-05",
                    f"Wall base ({wall.base_elevation:.2f}m) is more than one storey "
                    f"away from floor datum ({floor.elevation_above_datum:.2f}m)")

            # ── Opening checks ──────────────────────────────────────────
            for j, op in enumerate(wall.openings):
                oid = f"opening:{op.id[:8]}"

                # O-01: opening must fit within wall length
                if op.offset_along_wall < -0.01:
                    err(oid, "O-01", f"Negative offset ({op.offset_along_wall:.2f}m)")
                if op.offset_along_wall + op.width > wall.length + 0.01:
                    err(oid, "O-01",
                        f"Opening extends past wall: offset({op.offset_along_wall:.2f}) + "
                        f"width({op.width:.2f}) = {op.offset_along_wall + op.width:.2f}m "
                        f"> wall length {wall.length:.2f}m")

                # O-02: opening must fit within wall height
                if op.sill_height + op.height > wall.height + 0.01:
                    err(oid, "O-02",
                        f"Opening exceeds wall height: sill({op.sill_height:.2f}) + "
                        f"height({op.height:.2f}) = {op.sill_height + op.height:.2f}m "
                        f"> wall height {wall.height:.2f}m")

                # O-03: opening dimensions must be positive
                if op.width <= 0:
                    err(oid, "O-03", f"Opening width={op.width}m ≤ 0")
                if op.height <= 0:
                    err(oid, "O-03", f"Opening height={op.height}m ≤ 0")

                # O-04: sill height must be non-negative
                if op.sill_height < -0.01:
                    err(oid, "O-04", f"Negative sill height ({op.sill_height:.2f}m)")

                # O-05: doors must start at floor level
                if op.kind in (OpeningKind.SINGLE_DOOR, OpeningKind.DOUBLE_DOOR):
                    if op.sill_height > 0.05:
                        warn(oid, "O-05",
                             f"Door has sill_height={op.sill_height:.2f}m — doors should start at floor level")

                # O-06: window sill should be above floor
                if op.kind == OpeningKind.WINDOW:
                    if op.sill_height < 0.3:
                        warn(oid, "O-06",
                             f"Window sill at {op.sill_height:.2f}m — "
                             f"residential code typically requires ≥0.6m for safety")

            # O-07: openings must not overlap each other
            sorted_ops = sorted(wall.openings, key=lambda o: o.offset_along_wall)
            for j in range(len(sorted_ops) - 1):
                a, b = sorted_ops[j], sorted_ops[j + 1]
                a_end = a.offset_along_wall + a.width
                if a_end > b.offset_along_wall + 0.01:
                    err(f"wall:{wall.id[:8]}", "O-07",
                        f"Openings overlap: [{a.offset_along_wall:.2f}–{a_end:.2f}] "
                        f"and [{b.offset_along_wall:.2f}–{b.offset_along_wall + b.width:.2f}]")

            # W-06: remaining wall material between openings — check pier widths
            # After subtracting all openings, each solid segment must be ≥ min pier width
            MIN_PIER = 0.10  # minimum 10cm of wall between openings
            solid_start = 0.0
            for op in sorted_ops:
                pier = op.offset_along_wall - solid_start
                if 0 < pier < MIN_PIER:
                    warn(f"wall:{wall.id[:8]}", "W-06",
                         f"Wall pier between openings is only {pier:.2f}m "
                         f"(minimum {MIN_PIER}m for structural integrity)")
                solid_start = op.offset_along_wall + op.width
            # Check trailing pier
            trailing = wall.length - solid_start
            if 0 < trailing < MIN_PIER and sorted_ops:
                warn(f"wall:{wall.id[:8]}", "W-06",
                     f"Trailing wall pier is only {trailing:.2f}m")

            # W-07: total opening width should not exceed wall length
            total_opening_w = sum(op.width for op in wall.openings)
            if total_opening_w > wall.length + 0.01:
                err(f"wall:{wall.id[:8]}", "W-07",
                    f"Total opening width ({total_opening_w:.2f}m) exceeds "
                    f"wall length ({wall.length:.2f}m)")

        # ── Space checks ────────────────────────────────────────────────
        for space in floor.spaces:
            sid = f"space:{space.name}"

            # S-01: ceiling must be above floor
            if space.ceiling_elevation <= space.floor_elevation:
                err(sid, "S-01",
                    f"Ceiling ({space.ceiling_elevation:.2f}m) ≤ "
                    f"floor ({space.floor_elevation:.2f}m)")

            # S-02: room height sanity
            rh = space.room_height()
            if rh < 2.0:
                warn(sid, "S-02", f"Room height {rh:.2f}m < 2.0m — below habitable minimum")
            elif rh > 6.0:
                warn(sid, "S-02", f"Room height {rh:.2f}m > 6.0m — verify for residential")

            # S-03: boundary must have ≥ 3 vertices
            nv = len(space.boundary.outer.vertices)
            if nv < 3:
                err(sid, "S-03", f"Boundary has {nv} vertices (minimum 3)")
                continue

            # S-04: area must be positive and reasonable
            area = space.computed_area()
            if area <= 0:
                err(sid, "S-04", f"Space area={area:.2f}m² ≤ 0 — degenerate polygon")
            elif area < 1.0:
                warn(sid, "S-04", f"Space area={area:.2f}m² < 1m² — unusably small")
            elif area > 500:
                warn(sid, "S-04", f"Space area={area:.2f}m² > 500m² — verify for apartment")

            # S-05: stored area must match computed area
            if space.area_sq_units is not None:
                computed = _polygon_area(space.boundary.outer)
                diff = abs(space.area_sq_units - computed)
                if diff > 0.5:
                    warn(sid, "S-05",
                         f"Stored area ({space.area_sq_units:.1f}m²) differs from "
                         f"computed ({computed:.1f}m²) by {diff:.1f}m²")

            # S-06: space floor elevation should match parent floor
            if abs(space.floor_elevation - floor.elevation_above_datum) > 1.0:
                warn(sid, "S-06",
                     f"Space floor elevation ({space.floor_elevation:.2f}m) deviates > 1m "
                     f"from floor datum ({floor.elevation_above_datum:.2f}m)")

        # S-07: overlapping spaces on the same floor
        bboxes = [(sp, sp.bounding_box()) for sp in floor.spaces]
        for i in range(len(bboxes)):
            for j in range(i + 1, len(bboxes)):
                sp_a, bb_a = bboxes[i]
                sp_b, bb_b = bboxes[j]
                if _rects_overlap(bb_a, bb_b):
                    warn(f"{fid}", "S-07",
                         f"Spaces overlap: '{sp_a.name}' and '{sp_b.name}'")

        # ── Slab checks ─────────────────────────────────────────────────
        for slab in floor.slabs:
            slid = f"slab:{slab.id[:8]}"

            # SL-01: slab thickness must be positive
            if slab.thickness <= 0:
                err(slid, "SL-01", f"Slab thickness={slab.thickness}m ≤ 0")
            elif slab.thickness > 1.0:
                warn(slid, "SL-01", f"Slab thickness={slab.thickness}m > 1m — verify")

            # SL-02: slab boundary must have ≥ 3 vertices
            if len(slab.boundary.outer.vertices) < 3:
                err(slid, "SL-02", "Slab boundary has < 3 vertices")

    return findings


def validate_or_raise(model: BuildingModel) -> None:
    """Validate and raise ValueError if any errors found."""
    findings = validate_model(model)
    if not findings:
        return
    errors = [f for f in findings if f.severity == Severity.ERROR]
    warnings = [f for f in findings if f.severity == Severity.WARNING]
    report = []
    if errors:
        report.append(f"\n{'='*60}")
        report.append(f"  STRUCTURAL VALIDATION FAILED — {len(errors)} error(s), {len(warnings)} warning(s)")
        report.append(f"{'='*60}")
        for f in errors:
            report.append(str(f))
    if warnings:
        if not errors:
            report.append(f"\n  Structural validation: {len(warnings)} warning(s)")
        for f in warnings:
            report.append(str(f))
    msg = "\n".join(report)
    if errors:
        raise ValueError(msg)
    print(msg)



# 3D Isometric Renderer
# ═══════════════════════════════════════════════════════════════════════════════

class IsometricRenderer:
    """Renders a BuildingModel as an isometric 3D projection."""

    # Isometric angles: 30° tilt
    COS30 = math.cos(math.radians(30))
    SIN30 = math.sin(math.radians(30))

    def __init__(self, model: BuildingModel, scale: float = 40):
        self.model = model
        self.scale = scale
        self._compute_bounds()

    def _iso(self, x: float, y: float, z: float) -> tuple[float, float]:
        """Convert 3D world coords to 2D isometric screen coords."""
        sx = (x - y) * self.COS30 * self.scale
        sy = -(x + y) * self.SIN30 * self.scale - z * self.scale
        return sx, sy

    def _compute_bounds(self) -> None:
        """Find screen-space bounding box of the entire model."""
        corners: list[tuple[float, float]] = []
        for floor in self.model.floors:
            z0 = floor.elevation_above_datum
            z1 = z0 + floor.floor_to_floor_height
            for space in floor.spaces:
                for v in space.boundary.outer.vertices:
                    corners.append(self._iso(v.x, v.y, z0))
                    corners.append(self._iso(v.x, v.y, z1))
        if not corners:
            self.sx_min = self.sy_min = 0; self.sx_max = self.sy_max = 400
            return
        self.sx_min = min(c[0] for c in corners) - 80
        self.sx_max = max(c[0] for c in corners) + 80
        self.sy_min = min(c[1] for c in corners) - 120
        self.sy_max = max(c[1] for c in corners) + 80

    def img_w(self) -> int: return int(self.sx_max - self.sx_min)
    def img_h(self) -> int: return int(self.sy_max - self.sy_min) + TITLE_H

    def to_px(self, x: float, y: float, z: float) -> tuple[int, int]:
        sx, sy = self._iso(x, y, z)
        return int(sx - self.sx_min), int(sy - self.sy_min) + TITLE_H

    def render(self, path: str) -> str:
        img = Image.new("RGB", (self.img_w(), self.img_h()), BG_COLOR)
        draw = ImageDraw.Draw(img)

        # Sort floors bottom-up, spaces back-to-front (painter's algorithm)
        for floor in sorted(self.model.floors, key=lambda f: f.elevation_above_datum):
            z0 = floor.elevation_above_datum

            # Draw floor slab
            self._draw_slab(draw, floor, z0)

            # Draw spaces (floor fills)
            for space in sorted(floor.spaces, key=lambda s: -(s.centroid().x + s.centroid().y)):
                self._draw_space_floor(draw, space, z0)

            # Draw walls back-to-front
            for wall in sorted(floor.walls, key=lambda w: -(w.start.x + w.start.y + w.end.x + w.end.y) / 2):
                self._draw_wall_3d(draw, wall)

        self._draw_title(draw)
        img.save(path)
        return path

    def _draw_slab(self, draw: ImageDraw.Draw, floor: Floor, z: float) -> None:
        """Draw the floor slab as an isometric quad."""
        # Use combined bounding box of all spaces
        min_x = min_y = float("inf"); max_x = max_y = float("-inf")
        for sp in floor.spaces:
            bb = sp.bounding_box()
            min_x = min(min_x, bb[0]); min_y = min(min_y, bb[1])
            max_x = max(max_x, bb[2]); max_y = max(max_y, bb[3])

        corners = [
            self.to_px(min_x, min_y, z), self.to_px(max_x, min_y, z),
            self.to_px(max_x, max_y, z), self.to_px(min_x, max_y, z),
        ]
        draw.polygon(corners, fill=SLAB_3D, outline=OUTLINE_3D)

    def _draw_space_floor(self, draw: ImageDraw.Draw, space: Space, z: float) -> None:
        """Draw the floor area of a space as a filled polygon."""
        verts = [self.to_px(v.x, v.y, z + 0.01) for v in space.boundary.outer.vertices]
        fill = FILL_COLORS.get(space.usage, DEFAULT_FILL)
        # Lighten slightly for 3D floor
        fill = tuple(min(255, c + 15) for c in fill)
        draw.polygon(verts, fill=fill, outline=OUTLINE_3D)

        # Label
        c = space.centroid()
        px, py = self.to_px(c.x, c.y, z + 0.01)
        font = _load_font(10)
        _ctxt(draw, px, py, space.name, font, LABEL_COLOR)

    def _draw_wall_3d(self, draw: ImageDraw.Draw, wall: Wall) -> None:
        """Draw a wall as a 3D extruded quad (front face + top face)."""
        z0 = wall.base_elevation
        z1 = z0 + wall.height

        # Wall centerline direction
        dx = wall.end.x - wall.start.x
        dy = wall.end.y - wall.start.y
        wl = wall.length
        if wl == 0:
            return

        # Normal perpendicular to wall (for thickness)
        nx = -dy / wl * wall.thickness / 2
        ny = dx / wl * wall.thickness / 2

        # 4 corners at base, 4 at top (outer face)
        bl = Point2D(wall.start.x + nx, wall.start.y + ny)
        br = Point2D(wall.end.x + nx, wall.end.y + ny)

        # Determine which faces to draw based on viewing direction
        # In isometric (x-y, 30°), we see the "south" and "east" faces
        # Front face (the side facing the camera)
        front = [
            self.to_px(bl.x, bl.y, z0),
            self.to_px(br.x, br.y, z0),
            self.to_px(br.x, br.y, z1),
            self.to_px(bl.x, bl.y, z1),
        ]
        draw.polygon(front, fill=WALL_3D_FRONT, outline=OUTLINE_3D)

        # Top face
        tl_inner = Point2D(wall.start.x - nx, wall.start.y - ny)
        tr_inner = Point2D(wall.end.x - nx, wall.end.y - ny)
        top = [
            self.to_px(bl.x, bl.y, z1),
            self.to_px(br.x, br.y, z1),
            self.to_px(tr_inner.x, tr_inner.y, z1),
            self.to_px(tl_inner.x, tl_inner.y, z1),
        ]
        draw.polygon(top, fill=WALL_3D_TOP, outline=OUTLINE_3D)

        # Draw openings as dark rectangles on the front face
        for op in wall.openings:
            self._draw_opening_3d(draw, wall, op, bl, br, z0)

    def _draw_opening_3d(self, draw: ImageDraw.Draw, wall: Wall, op: Opening,
                          bl: Point2D, br: Point2D, z0: float) -> None:
        """Draw an opening as a dark rectangle on the wall face."""
        wl = wall.length
        if wl == 0:
            return

        t0 = op.offset_along_wall / wl
        t1 = (op.offset_along_wall + op.width) / wl
        t0 = max(0, min(1, t0))
        t1 = max(0, min(1, t1))

        # Interpolate along the outer face edge
        ox0 = bl.x + (br.x - bl.x) * t0
        oy0 = bl.y + (br.y - bl.y) * t0
        ox1 = bl.x + (br.x - bl.x) * t1
        oy1 = bl.y + (br.y - bl.y) * t1

        oz_bot = z0 + op.sill_height
        oz_top = oz_bot + op.height

        opening_quad = [
            self.to_px(ox0, oy0, oz_bot),
            self.to_px(ox1, oy1, oz_bot),
            self.to_px(ox1, oy1, oz_top),
            self.to_px(ox0, oy0, oz_top),
        ]
        if op.kind == OpeningKind.WINDOW:
            # Windows: light blue tint (glass) with a cross mullion
            window_fill = (45, 70, 115)
            draw.polygon(opening_quad, fill=window_fill, outline=OUTLINE_3D)
            # Horizontal mullion at mid-height
            mz = (oz_bot + oz_top) / 2
            ml = self.to_px(ox0, oy0, mz)
            mr = self.to_px(ox1, oy1, mz)
            draw.line([ml, mr], fill=WALL_COLOR, width=1)
            # Vertical mullion at mid-width
            mx = (ox0 + ox1) / 2
            my = (oy0 + oy1) / 2
            mt = self.to_px(mx, my, oz_top)
            mb = self.to_px(mx, my, oz_bot)
            draw.line([mt, mb], fill=WALL_COLOR, width=1)
        else:
            # Doors: dark void
            draw.polygon(opening_quad, fill=OPENING_3D, outline=OUTLINE_3D)

    def _draw_title(self, draw: ImageDraw.Draw) -> None:
        ft, fs = _load_font(22), _load_font(13)
        cx = self.img_w() // 2
        _ctxt(draw, cx, 30, self.model.title, ft, TITLE_COLOR)
        area = sum(s.computed_area() for f in self.model.floors for s in f.spaces)
        _ctxt(draw, cx, 60, f"{self.model.building.name}  |  ~{area:.0f} m²  |  3D Isometric", fs, DIM_COLOR)



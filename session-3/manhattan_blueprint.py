def main() -> None:
    parser = argparse.ArgumentParser(
        description="Manhattan Apartment Blueprint & 3D Generator",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=(
            "Layouts: studio (~42 m²), 1br (~65 m²), 2br (~79 m²), luxury (~111 m²), all\n"
            "Outputs: blueprint_*.png (2D plan) + model_*.png (3D isometric)\n"
        ),
    )
    parser.add_argument("layout", nargs="?", default="all",
                        choices=[*LAYOUTS.keys(), "all"])
    parser.add_argument("-o", "--output-dir", default=".")
    parser.add_argument("--skip-validation", action="store_true",
                        help="Skip structural validation (render even if invalid)")
    args = parser.parse_args()

    out = Path(args.output_dir); out.mkdir(parents=True, exist_ok=True)
    keys = LAYOUTS.keys() if args.layout == "all" else [args.layout]

    for key in keys:
        model = LAYOUTS[key]()

        # Structural validation — errors halt, warnings print
        if not args.skip_validation:
            validate_or_raise(model)

        bp_path = out / f"blueprint_{key}.png"
        BlueprintRenderer(model).render(str(bp_path))
        print(f"  2D -> {bp_path}")

        iso_path = out / f"model_{key}.png"
        IsometricRenderer(model).render(str(iso_path))
        print(f"  3D -> {iso_path}")

    print("Done.")


if __name__ == "__main__":
    main()

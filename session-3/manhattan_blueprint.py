class BlueprintRenderer:
    def __init__(self, model: BuildingModel):
        self.model = model
        self._compute_bounds()

    def _compute_bounds(self) -> None:
        min_x = min_y = float("inf"); max_x = max_y = float("-inf")
        for floor in self.model.floors:
            for space in floor.spaces:
                sx0, sy0, sx1, sy1 = space.bounding_box()
                min_x = min(min_x, sx0); min_y = min(min_y, sy0)
                max_x = max(max_x, sx1); max_y = max(max_y, sy1)
        self.plan_w = max_x - min_x; self.plan_h = max_y - min_y
        self.off_x = min_x; self.off_y = min_y

    def img_w(self) -> int: return int(self.plan_w * PX_PER_UNIT) + PADDING * 2
    def img_h(self) -> int: return int(self.plan_h * PX_PER_UNIT) + PADDING * 2 + TITLE_H + LEGEND_H

    def to_px(self, x: float, y: float) -> tuple[int, int]:
        return (PADDING + int((x - self.off_x) * PX_PER_UNIT),
                PADDING + TITLE_H + int((y - self.off_y) * PX_PER_UNIT))

    def render(self, path: str) -> str:
        img = Image.new("RGB", (self.img_w(), self.img_h()), BG_COLOR)
        draw = ImageDraw.Draw(img)
        self._grid(draw)
        for f in self.model.floors:
            self._spaces(draw, f)
            self._walls_2d(draw, f)
        self._dims(draw); self._title(draw); self._legend(draw)
        img.save(path); return path

    def _grid(self, d: ImageDraw.Draw) -> None:
        x0, y0 = self.to_px(self.off_x, self.off_y)
        x1, y1 = self.to_px(self.off_x + self.plan_w, self.off_y + self.plan_h)
        for m in range(int(self.plan_w) + 1):
            px, _ = self.to_px(self.off_x + m, self.off_y)
            if x0 <= px <= x1: d.line([(px, y0), (px, y1)], fill=GRID_COLOR)
        for m in range(int(self.plan_h) + 1):
            _, py = self.to_px(self.off_x, self.off_y + m)
            if y0 <= py <= y1: d.line([(x0, py), (x1, py)], fill=GRID_COLOR)

    def _spaces(self, d: ImageDraw.Draw, floor: Floor) -> None:
        fl, fa, fd = _load_font(14), _load_font(11), _load_font(10)
        for sp in floor.spaces:
            pxv = [self.to_px(v.x, v.y) for v in sp.boundary.outer.vertices]
            fill = FILL_COLORS.get(sp.usage, DEFAULT_FILL)
            d.polygon(pxv, fill=fill); d.polygon(pxv, outline=WALL_COLOR, width=WALL_PX)
            bb = sp.bounding_box()
            px0, py0 = self.to_px(bb[0], bb[1]); px1, py1 = self.to_px(bb[2], bb[3])
            cx, cy = (px0+px1)//2, (py0+py1)//2
            rpw, rph = abs(px1-px0), abs(py1-py0)
            w, h = bb[2]-bb[0], bb[3]-bb[1]
            area = sp.computed_area()
            if rpw > 50 and rph > 40:
                _ctxt(d, cx, cy-14, sp.name, fl, LABEL_COLOR)
                _ctxt(d, cx, cy+4, f"{area:.1f} m²", fa, DIM_COLOR)
                if rph > 60: _ctxt(d, cx, cy+20, f"{w:.1f} × {h:.1f} m", fd, DIM_COLOR)
            elif rpw > 30 and rph > 24:
                _ctxt(d, cx, cy-4, sp.name, fa, LABEL_COLOR)

    def _walls_2d(self, d: ImageDraw.Draw, floor: Floor) -> None:
        for wall in floor.walls:
            sx, sy = self.to_px(wall.start.x, wall.start.y)
            ex, ey = self.to_px(wall.end.x, wall.end.y)
            w = max(2, int(wall.thickness * PX_PER_UNIT))
            d.line([(sx,sy),(ex,ey)], fill=WALL_COLOR, width=w)
            for op in wall.openings:
                self._opening_2d(d, wall, op)

    def _opening_2d(self, d: ImageDraw.Draw, wall: Wall, op: Opening) -> None:
        wl = wall.length
        if wl == 0: return
        ux = (wall.end.x - wall.start.x) / wl
        uy = (wall.end.y - wall.start.y) / wl
        # Normal perpendicular to wall direction
        nx, ny = -uy, ux
        sx = wall.start.x + ux * op.offset_along_wall
        sy = wall.start.y + uy * op.offset_along_wall
        ex = wall.start.x + ux * (op.offset_along_wall + op.width)
        ey = wall.start.y + uy * (op.offset_along_wall + op.width)
        psx, psy = self.to_px(sx, sy); pex, pey = self.to_px(ex, ey)
        w = max(2, int(wall.thickness * PX_PER_UNIT)) + 2
        d.line([(psx,psy),(pex,pey)], fill=BG_COLOR, width=w)
        if op.kind in (OpeningKind.SINGLE_DOOR, OpeningKind.DOUBLE_DOOR):
            # Door arc
            dp = int(op.width * PX_PER_UNIT); half = dp // 2
            mcx, mcy = (psx+pex)//2, (psy+pey)//2
            d.arc([mcx-half, mcy-half, mcx+half, mcy+half], 180, 270, fill=DOOR_ARC_COLOR)
        elif op.kind == OpeningKind.WINDOW:
            # Window: draw a thin double line across the gap with tick marks
            # The double line represents the glass pane in plan view
            t = wall.thickness * PX_PER_UNIT * 0.3  # offset for double line
            pnx, pny = int(nx * t), int(ny * t)
            # Two parallel lines (glass panes)
            d.line([(psx+pnx, psy+pny), (pex+pnx, pey+pny)], fill=WALL_COLOR, width=1)
            d.line([(psx-pnx, psy-pny), (pex-pnx, pey-pny)], fill=WALL_COLOR, width=1)
            # Tick marks at each end (perpendicular to wall)
            tick = int(wall.thickness * PX_PER_UNIT * 0.6)
            tnx, tny = int(nx * tick), int(ny * tick)
            d.line([(psx-tnx, psy-tny), (psx+tnx, psy+tny)], fill=WALL_COLOR, width=1)
            d.line([(pex-tnx, pey-tny), (pex+tnx, pey+tny)], fill=WALL_COLOR, width=1)

    def _outer(self, d: ImageDraw.Draw) -> None:
        x0, y0 = self.to_px(self.off_x, self.off_y)
        x1, y1 = self.to_px(self.off_x+self.plan_w, self.off_y+self.plan_h)
        d.rectangle([x0,y0,x1,y1], outline=WALL_COLOR, width=WALL_PX+2)

    def _dims(self, d: ImageDraw.Draw) -> None:
        f = _load_font(10); off = 30
        x0, y0 = self.to_px(self.off_x, self.off_y)
        x1, y1 = self.to_px(self.off_x+self.plan_w, self.off_y+self.plan_h)
        _dim_h(d, x0, y0-off, x1, y0-off, f"{self.plan_w:.1f} m", f)
        _dim_v(d, x0-off, y0, x0-off, y1, f"{self.plan_h:.1f} m", f)

    def _title(self, d: ImageDraw.Draw) -> None:
        ft, fs = _load_font(22), _load_font(13)
        cx = self.img_w() // 2
        d.line([(PADDING, PADDING+TITLE_H-8), (self.img_w()-PADDING, PADDING+TITLE_H-8)], fill=WALL_COLOR, width=2)
        _ctxt(d, cx, PADDING+10, self.model.title, ft, TITLE_COLOR)
        area = sum(s.computed_area() for f in self.model.floors for s in f.spaces)
        _ctxt(d, cx, PADDING+42, f"{self.model.building.name}  |  ~{area:.0f} m²  |  1:100", fs, DIM_COLOR)

    def _legend(self, d: ImageDraw.Draw) -> None:
        f = _load_font(10); yb = self.img_h() - LEGEND_H + 15; x = PADDING
        d.line([(PADDING, yb-10), (self.img_w()-PADDING, yb-10)], fill=WALL_COLOR)
        for fl in self.model.floors:
            for sp in fl.spaces:
                bb = sp.bounding_box(); w, h = bb[2]-bb[0], bb[3]-bb[1]
                lbl = f"{sp.name}: {w:.1f}×{h:.1f} m ({sp.computed_area():.1f} m²)"
                tw = f.getbbox(lbl)[2] - f.getbbox(lbl)[0]
                if x+tw+20 > self.img_w()-PADDING: yb += 16; x = PADDING
                d.text((x, yb), lbl, fill=DIM_COLOR, font=f); x += tw + 24



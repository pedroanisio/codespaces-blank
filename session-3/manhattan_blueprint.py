def _load_font(size: int) -> ImageFont.FreeTypeFont:
    for p in ["/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
              "/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf",
              "/System/Library/Fonts/Helvetica.ttc"]:
        if Path(p).exists(): return ImageFont.truetype(p, size)
    return ImageFont.load_default()

def _ctxt(d: ImageDraw.Draw, cx: int, cy: int, text: str, font, color: tuple) -> None:
    bb = font.getbbox(text)
    d.text((cx - (bb[2]-bb[0])//2, cy - (bb[3]-bb[1])//2), text, fill=color, font=font)

def _dim_h(d, x0, y, x1, y2, label, font):
    s = 6; d.line([(x0,y),(x1,y)], fill=DIM_COLOR)
    d.line([(x0,y-s),(x0,y+s)], fill=DIM_COLOR); d.line([(x1,y-s),(x1,y+s)], fill=DIM_COLOR)
    _ctxt(d, (x0+x1)//2, y-12, label, font, DIM_COLOR)

def _dim_v(d, x, y0, x2, y1, label, font):
    s = 6; d.line([(x,y0),(x,y1)], fill=DIM_COLOR)
    d.line([(x-s,y0),(x+s,y0)], fill=DIM_COLOR); d.line([(x-s,y1),(x+s,y1)], fill=DIM_COLOR)
    bb = font.getbbox(label)
    tw, th = bb[2]-bb[0], bb[3]-bb[1]
    ti = Image.new("RGBA", (tw+4, th+4), (0,0,0,0))
    ImageDraw.Draw(ti).text((2,2), label, fill=DIM_COLOR, font=font)
    r = ti.rotate(90, expand=True)
    d._image.paste(r, (x-r.width//2, (y0+y1)//2-r.height//2), r)


